// Правка: сделай модуль более ступенчатым.
exports.options = { corner: true };
exports.build = r => {
  r.desc('Дозорный угол поднимается уступами 1,25, 3, 4,5 и 6,25 м к гребню в юго-западном углу, где стрелок, жаровня и большой сундук. На 3 м кольцо: западный вал, центральный бастион и южный вал сшиты двумя мостами, под которыми идёт траншея с тайником между северным и восточным дворами. Наверх три пути: с северо-запада по валу, с севера прямо на бастион и с юго-востока. Дворы разбиты тремя приступками 1,25–2 м с лестницами.');
  r.level(0, 10).carve(-16.8, -16.8, 16.8, 16.8);
  // up: марш от нижней кромки (x, z) в сторону dir; длина из уклона 0,77.
  const dirs = { N: [0, 1, 0], E: [1, 0, 90], S: [0, -1, 180], W: [-1, 0, 270] };
  const up = (x, z, w, rise, dir, y0 = 0) => { const [dx, dz, ry] = dirs[dir], len = Math.ceil(rise * 13) / 10; r.stairs(x + dx * len / 2, z + dz * len / 2, w, len, rise, ry, y0); };

  // Уступы к гребню.
  r.platform(-16.8, 3, -9, 10, 1.25);          // северо-западная ступень
  r.platform(-16.8, -6, -8, 3, 3);             // западный вал
  r.platform(-16.8, -16.8, -6, -6, 4.5);       // подножие гребня
  r.platform(-16.8, -16.8, -10, -11.5, 6.25);  // гребень
  r.platform(-6, -16.8, 3, -9, 3);             // южный вал
  r.platform(3, -16.8, 9, -9, 1.5);            // нижняя ступень южного вала
  r.platform(-3, -4, 7, 3, 3);                 // центральный бастион
  // Мосты над траншеей.
  r.slab(-8, -2, -3, 0.4, 3);
  r.slab(0, -9, 2.4, -4, 3);

  // Северо-западный путь.
  up(-11.4, 11.7, 2.4, 1.25, 'S');
  up(-12, 4.95, 2.4, 1.75, 'S', 1.25);
  up(-12, -2.05, 2.6, 1.5, 'S', 3);
  up(-7.6, -14, 2.2, 1.75, 'W', 4.5);
  // Северный, прямо на бастион.
  up(2, 6.95, 2.4, 3, 'S');
  // Юго-восточный: двор, нижняя ступень, южный вал, подножие гребня.
  up(11.1, -13, 2.4, 1.5, 'W');
  up(5, -11.5, 2.4, 1.5, 'W', 1.5);
  up(-3.95, -12, 2.4, 1.5, 'W', 3);

  // Приступки дворов.
  r.platform(-4, 10, 4, 16.8, 2);
  up(-2.2, 7.4, 2.4, 2, 'N');
  r.platform(11, -3.6, 16.8, 4, 1.5);
  up(9, 0.4, 2.4, 1.5, 'E');
  r.platform(12, 12, 16.8, 16.8, 1.25);
  up(10.3, 14.2, 2.4, 1.25, 'E');

  // Парапеты: укрытие стрелкам.
  r.prop('Парапет', -13.4, -11.65, 6.8, 0.3, 1, { y: 6.25 });
  r.prop('Парапет', -10.15, -12.1, 0.3, 0.9, 1, { y: 6.25 });
  r.prop('Парапет', -10.15, -16, 0.3, 1.6, 1, { y: 6.25 });
  r.prop('Парапет', 2, -3.85, 8, 0.3, 1, { y: 3 });
  r.prop('Парапет', 6.85, 0, 0.3, 6, 1, { y: 3 });
  r.prop('Парапет', -2.85, 1.6, 0.3, 2.4, 1, { y: 3 });
  r.prop('Парапет', 1.8, 10.15, 3.6, 0.3, 1, { y: 2 });
  r.prop('Парапет', 11.15, -2, 0.3, 2.4, 1, { y: 1.5 });
  // Укрытия внизу.
  r.column(12, -7);
  r.column(-14, 13.5);
  r.prop('Обломки', -6, 7.5, 1.8, 2, 0.9);
  r.prop('Штабель ящиков', 8.2, 5.8, 2, 1.4, 1.4);
  r.prop('Обломки', -5.6, -6.5, 2, 1.6, 0.9);

  r.chest('LargeOakChest', -15.2, -15.4, { y: 6.25, ry: 45 });
  r.chest('SmallOakChest', 3, -6.5, { ry: 90 });
  r.chest('Urn', -15.8, 8.6, { y: 1.25 });
  r.chest('Crate', 15.6, -15.6);
  r.chest('Urn', 3, 15.8, { y: 2 });
  r.chest('Barrel', 15.8, 15.8, { y: 1.25 });
  r.monster('Archer', -13, -13.5, { y: 6.25, ry: 45 });
  r.monster('Archer', 3, 0, { y: 3, ry: 90 });
  r.monster('Warrior', -9, -9, { y: 4.5, ry: 90 });
  r.monster('Sword', -5.5, 0, { ry: 0 });
  r.monster('Crossbow', -2, -14, { y: 3, ry: 90 });
  r.monster('Crossbow', 14, 0.5, { y: 1.5, ry: 270 });

  r.brazier(-15.6, -12.8, 6.25);
  r.brazier(0, 1.5, 3);
  r.brazier(0, 15, 2);
  r.torch(-16.4, 6, 90, 1.25);
  r.torch(16.4, 7, 270);
  r.torch(4, -16.4, 0, 3);
  r.candle(1.5, -6.5);
  r.start(6, 13, 225);
};
