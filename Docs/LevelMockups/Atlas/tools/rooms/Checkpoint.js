  for (const [x, z] of [[-1.1, -10], [0.9, -5], [-1.1, 7], [0.9, 2], [-5.1, 1.2], [4.9, -1.2], [-8, -9.9], [-8, 9.9], [-8, -1.2], [-8, 1.2]]) r.column(x, z, { s: 0.4, h: BELOW });
