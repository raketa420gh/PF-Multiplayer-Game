  r.wall(-16.8, -1.5, -11.6, -1.5, { h: 3.4, th: 0.8 });
  for (const [x, z, w, d] of [[-9.5, 5, 0.6, 4], [-9.5, -5, 0.6, 4], [-11.6, 4.2, 0.6, 3], [-7.6, -7.6, 3, 0.6], [-7.6, 7.8, 3, 0.6], [-15.4, 3, 2.2, 0.6]]) stone(x, z, w, d);
  r.prop('Стойка с оружием', -16.3, -13, 0.6, 3, 1.8); r.prop('Кости', -7, 3.4, 1.4, 1, 0.2); r.prop('Мешки', -14.6, 13.6, 1.6, 1, 0.8);
  r.block(-11.5, -9.6, 2.4, 1.6, { h: 2.2 }); r.prop('Обломки', -11, 12, 1.8, 1.2, 0.9, { ry: 20 });
