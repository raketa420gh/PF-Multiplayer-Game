  r.prop('Стол', 15, 3.4, 1, 2.4, 0.8); r.prop('Лавка', 13.6, -2.8, 3, 0.5, 0.5); r.chest('Crate', 16, -4.4);
  r.prop('Штабель ящиков', 15.6, 14.8, 1.6, 1.6, 2); r.prop('Бочки', 11.5, -14.2, 1.4, 1.4, 1.2); r.prop('Мешки', 5.9, 14.8, 1.4, 1, 0.8);
