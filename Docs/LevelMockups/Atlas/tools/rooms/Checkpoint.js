  r.chest('LargeOakChest', 11.4, 11.2, { y: DECK, ry: 270 }); r.prop('Стол', 9.4, 11, 2.2, 0.9, 0.8, { y: DECK }); r.prop('Койка', 11.7, 7, 0.9, 2, 0.5, { y: DECK }); r.monster('Crossbow', 9.6, 7.4, { y: DECK, ry: 270 });
