// Новая: недостроенный колосс императора на всю высоту 24 м в строительных лесах, полости в ноге, животе и голове.
const { subtract, rect } = require('../roomkit');
const P = 3.2, B = 10, HT = 20; // верх постамента, пол живота, пол головы

exports.options = {};
exports.build = r => {
  r.desc('Зал 24 м, посреди него недостроенная статуя императора: постамент 3,2 м, две ноги, торс, плечи до +16, голова до +23 с недобитым лицом. Вокруг леса на 5, 10, 15 и 20 м с разрывами: два марша на +5 с запада и востока, на запад выше по маршу на +10, дальше леса кругом через север на восток, марш на +15, вокруг груди на запад и марш на +20, откуда мостки за спиной ведут в голову с лучшей добычей. Левая нога полая: с постамента лестница в два марша поднимается в камеру в животе с сундуком, пролом в спине выводит её на леса +10. На полу каменоломня: блоки, кран и хижины каменщиков с дверями, они прикрывают проёмы.');
  r.level(0, 24).carve(-16.8, -16.8, 16.8, 16.8);
  const box = (x1, y1, z1, x2, y2, z2, ry) => r.block((x1 + x2) / 2, (z1 + z2) / 2, x2 - x1, z2 - z1, { y: y1, h: y2 - y1, ry });
  const slabs = (area, y, holes) => subtract(area, holes).forEach(q => r.slab(q.x1, q.z1, q.x2, q.z2, y));
  const pole = (x, z, h) => r.column(x, z, { s: 0.4, h: h - 0.6 });

  // ---------- Статуя ----------
  r.platform(-8, -6, 8, 6, P);
  r.stairs(-3.4, -7.9, 4, 3.8, P, 0);                                    // парадный подъём с юга
  r.stairs(5.4, 7.9, 2.4, 3.8, P, 180);                                  // рабочий подъём с севера
  box(-6, P, -3.4, -1.4, 9.4, 3.4);                                      // правая нога, цельная
  // Левая нога: полая, вход с постамента с юга.
  const X1 = 1.4, X2 = 6.6, Z1 = -3.6, Z2 = 3.6, T = 0.6, Top = 9.4;
  r.doorWall(X1, Z1, X2, Z1, [5.1], { th: T, y: P, h: Top - P, door: false });
  r.wall(X1, Z2, X2, Z2, { th: T, y: P, h: Top - P });
  r.wall(X1, Z1 + 0.3, X1, Z2 - 0.3, { th: T, y: P, h: Top - P }); r.wall(X2, Z1 + 0.3, X2, Z2 - 0.3, { th: T, y: P, h: Top - P });
  r.stairs(5.1, 0.4, 1.8, 4, 3.4, 0, P);
  r.slab(2, 2.4, 6, 3.3, 6.6);
  r.stairs(2.9, 0.4, 1.8, 4, 3.4, 180, 6.6);
  // Живот: камера, западнее цельный камень, пролом в спине на леса.
  slabs(rect(1.7, -3.3, 6.3, 3.3), B, [rect(2, -1.6, 3.8, 2.4)]);
  box(-5.7, 9.4, -3.6, 1.4, B, 3.6);
  r.slab(-1.4, -3.3, 1.7, 3.3, B); r.slab(-0.8, 3.3, 1.6, 4, B);
  r.wall(-1.7, -3.6, 6.6, -3.6, { th: T, y: Top, h: 4 }); r.doorWall(-1.7, 3.6, 6.6, 3.6, [0.4], { th: T, y: B, h: 3.4, door: false });
  r.wall(6.6, -3.3, 6.6, 3.3, { th: T, y: Top, h: 4 }); r.wall(-1.7, -3.3, -1.7, 3.3, { th: T, y: Top, h: 4 });
  box(-6, Top, -3.6, -2, 13.4, 3.6);
  r.slab(-2, -3.9, 6.9, 3.9, 14);
  r.chest('LargeOakChest', -0.8, -2.2, { y: B, ry: 0 }); r.chest('Urn', 5.6, -2.6, { y: B }); r.prop('Кости', 3.8, -2.4, 1.4, 1, 0.2, { y: B }); r.candle(-0.6, -0.6, B); r.monster('Skull', 0.6, 0.6, { y: B, ry: 90 });
  // Плечи, рука-заготовка, шея, голова.
  box(-9, 14, -3.8, 9, 16, 3.8);
  box(-9, 8, -3, -6.4, 14, 3); box(6.8, 11, -3, 9, 14, 2.4);
  box(-2, 16, -2, 2, 17.2, 2);
  // Голова: стены, северный проём, пол; лицо брошено на полпути.
  const HW = 3.2, HZ1 = -3.2, HZ2 = 3.2, HTop = 23.2;
  box(-HW, 17.2, HZ1, HW, HT - 0.6, HZ2);
  r.slab(-HW, HZ1, HW, HZ2, HT);
  r.wall(-HW, HZ1, HW, HZ1, { th: 0.6, y: HT, h: HTop - HT - 0.5 }); r.wall(-HW, HZ1 + 0.3, -HW, HZ2 - 0.3, { th: 0.6, y: HT, h: HTop - HT - 0.5 }); r.wall(HW, HZ1 + 0.3, HW, HZ2 - 0.3, { th: 0.6, y: HT, h: HTop - HT - 0.5 });
  r.doorWall(-HW, HZ2, HW, HZ2, [1], { th: 0.6, y: HT, h: HTop - HT - 0.5, door: false });
  box(-HW - 0.3, HTop - 0.5, HZ1 - 0.3, HW + 0.3, HTop, HZ2 + 0.3);
  box(-3, 21.4, -4.1, 0.2, 22.4, -3.5); box(-1.4, 19.4, -4.5, 0.4, 21.4, -3.5, 12); box(-0.9, 18.2, -4, 0.9, 19, -3.5); // бровь, нос, подбородок; правая половина лица сырой блок
  box(0.6, 18, -4.3, 3.1, 22.8, -3.5);
  r.chest('GoldenChest', -1.6, -1.6, { y: HT, ry: 45 }); r.chest('GoldPile', -2, 0.6, { y: HT }); r.chest('GoldPile', 1.2, -2, { y: HT });
  r.trap('Spike', 1, 1.2, { y: HT }); r.trap('Vent', -0.2, 0, { y: HT }); r.trap('Spike', 1.4, -0.2, { y: HT }); r.brazier(2, 2, HT); r.monster('Warrior', 0.2, -1, { y: HT, ry: 0 });

  // ---------- Леса +5: разрыв на юге, с востока приходят только через север ----------
  r.slab(-14.6, 2, -10.8, 4, 5); r.slab(-10.8, -8, -8.8, 8, 5); r.slab(-8.8, 6, 10.8, 8, 5); r.slab(8.8, -2, 10.8, 6, 5); r.slab(10.8, -2, 14.4, 0, 5);
  // Леса +10: разрыв на юге.
  r.slab(-12.6, -6, -9, -4, B); r.slab(-10.8, -4, -9, 4, B); r.slab(-10.8, 4, 12.6, 6, B); r.slab(9, -4, 10.8, 4, B); r.slab(10.8, 2, 12.6, 4, B);
  // Леса +15: разрыв на севере, кругом только через грудь статуи.
  r.slab(-12.6, -6, 12.6, -4, 15);
  // Леса +20: мостки за спиной к голове.
  r.slab(-12.6, 2, -10.8, 3.5, HT); r.slab(-12.6, 3.5, 2.2, 5.2, HT); r.slab(0, HZ2, 2, 3.5, HT);
  r.stairs(-13.7, -1, 1.8, 6, 5, 0);                                     // запад 0 → 5
  r.stairs(-11.7, -1, 1.8, 6, 5, 180, 5);                                // запад 5 → 10
  r.stairs(-11.7, -1, 1.8, 6, 5, 0, 15);                                 // запад 15 → 20
  r.stairs(13.5, 3, 1.8, 6, 5, 180);                                     // восток 0 → 5
  r.stairs(11.7, -1, 1.8, 6, 5, 180, B);                                 // восток 10 → 15
  for (const [x, z] of [[-14.4, 3.8], [-11, 3.8], [-10.6, 7.8], [-9, 7.8], [-3, 7.8], [3, 7.8], [8.9, 7.8], [10.6, 5.8], [14.2, -1.8], [12.4, 3.8], [12.4, -3.8]]) pole(x, z, 5);
  for (const [x, z] of [[-10.6, 5.8], [-10.6, -3.8], [-12.4, -5.8], [-3, 5.8], [3, 5.8], [10.6, 5.8], [10.6, -3.8], [12.4, 2.2]]) pole(x, z, B);
  for (const [x, z] of [[-12.4, -5.8], [-4, -5.8], [4, -5.8], [12.4, -5.8]]) pole(x, z, 15);
  for (const [x, z] of [[-12.4, 2.2], [-12.4, 5], [-5, 5], [1.6, 5]]) pole(x, z, HT);
  r.chest('Crate', -9.8, -7.2, { y: 5 }); r.chest('SmallOakChest', 9.8, -3.4, { y: B, ry: 90 }); r.chest('Crate', -7, 5, { y: B }); r.chest('Urn', 2, -5, { y: 15 });

  // ---------- Каменоломня ----------
  // Хижина: одна комната, кровля, можно закрыть ею проход к стене.
  const hut = (x1, z1, x2, z2, { N, S, E, W }, h = 3.2) => {
    const o = { th: 0.4, h };
    if (z2 < 16.8) r.doorWall(Math.max(x1 - 0.2, -16.8), z2, Math.min(x2 + 0.2, 16.8), z2, N || [], o);
    if (z1 > -16.8) r.doorWall(Math.max(x1 - 0.2, -16.8), z1, Math.min(x2 + 0.2, 16.8), z1, S || [], o);
    if (x2 < 16.8) r.doorWall(x2, z1 + 0.2, x2, z2 - 0.2, E || [], o);
    if (x1 > -16.8) r.doorWall(x1, z1 + 0.2, x1, z2 - 0.2, W || [], o);
    r.slab(Math.max(x1 - 0.3, -16.8), Math.max(z1 - 0.3, -16.8), Math.min(x2 + 0.3, 16.8), Math.min(z2 + 0.3, 16.8), h + 0.6);
  };
  hut(-16.8, 11, -11, 16.8, { S: [-13] }); r.prop('Койка', -15.8, 15, 0.9, 1.9, 0.5); r.prop('Стол', -12.6, 15.6, 1.2, 0.8, 0.8); r.chest('Crate', -15.8, 12.2);
  hut(-5, 11.4, 4.6, 16.8, { S: [-2.4], E: [] }); r.doorWall(0.4, 11.6, 0.4, 16.8, [14], { th: 0.3, h: 3.2 }); r.prop('Верстак', -3.4, 15.8, 2.6, 0.9, 0.9); r.prop('Койка', 3.4, 15, 0.9, 1.9, 0.5); r.chest('LargeOakChest', 3.6, 12.4, { ry: 270 });
  hut(11.2, 11, 16.8, 16.8, { W: [14.2] }); r.prop('Койка', 15.8, 15, 0.9, 1.9, 0.5); r.prop('Штабель ящиков', 15.6, 12.2, 1.3, 1.3, 2);
  hut(-4.6, -16.8, 3.4, -11.4, { N: [-1.4] }); r.prop('Стойка с оружием', 1, -16.2, 3, 0.6, 2); r.prop('Стол', -3.4, -13, 0.8, 1.4, 0.8); r.chest('SmallOakChest', 2.6, -13, { ry: 270 });
  hut(-16.8, -16.8, -11.2, -11.4, { E: [-14.2] }); r.prop('Полки с припасами', -14, -16.2, 3.4, 0.5, 2.2); r.chest('Barrel', -15.8, -12.4);
  // Блоки у стен рвут кольцо, штабеля в проходах прикрывают проёмы.
  for (const [x, z, w, d, h, ry] of [[15.4, -3, 2.8, 3.4, 3.6, 0], [-15.8, 0.4, 2, 4, 3, 0], [14, -13.2, 5.6, 7.2, 2.6, 0], [8.4, -9.4, 3.2, 2, 1.8, 12], [-7.6, -9.6, 2.4, 1.8, 2, 345], [7.4, 11.6, 2.2, 1.6, 1.8, 20], [-8.8, 11.2, 1.6, 2, 1.4, 10], [1.6, 8.5, 3.4, 1.4, 2.2, 6]]) r.block(x, z, w, d, { h, ry });
  r.prop('Обломки', -11, 6.8, 1.6, 1.2, 0.9, { ry: 20 }); r.prop('Рудная вагонетка', 12.6, 9, 2, 1.2, 1.2, { ry: 5 }); r.prop('Обломки', 11.6, -8, 1.8, 1.2, 0.9, { ry: 35 }); r.prop('Стойка с оружием', -13, -9.6, 2, 0.6, 1.8);
  // Кран: мачта, стрела над грудью статуи, глыба на тросе.
  r.column(12.2, -12.4, { s: 0.9, y: 2.6, h: 16.4 }); box(-1, 19, -12.8, 14, 19.8, -12);
  r.prop('Трос', 2, -12.4, 0.16, 0.16, 11, { y: 8 }); box(0.8, 5.8, -13.6, 3.2, 8, -11.2);

  r.brazier(-10, 9.6); r.brazier(9.8, -10.4); r.torch(-16.6, 6, 90, 0); r.torch(16.6, 2, 270, 2); r.torch(0, -7.9, 0, 10); r.torch(-12.5, -6.2, 0, 10); r.torch(0, 5.5, 180, 12); r.torch(-3.3, 5, 90, HT - 1.2);
  r.monster('Sword', 9.6, 2, { ry: 270 }); r.monster('Sword', -5, -11, { ry: 0 }); r.monster('Archer', 4, 7, { y: 5, ry: 180 }); r.monster('Crossbow', -9.8, 1.2, { y: B, ry: 90 }); r.monster('Archer', -6, -5, { y: 15, ry: 0 });
  r.start(8.4, 14, 180);
};
