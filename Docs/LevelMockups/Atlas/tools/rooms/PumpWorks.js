// Новая: шахта водоотлива на всю высоту занята двумя колёсами-топчаками, мостки и марши идут сквозь машину, лифт-клеть до дна.
const MID = -5, BOT = -10, DECK = -9.75;
const SX = 7.2, SZ = 8.4;

exports.options = {};
exports.build = r => {
  r.desc('В центре клетки шахта водоотлива 14,4 × 16,8 м от 0 до −10, на дне вода, а внутри две огромные машины: колёса-топчаки диаметром 8 м на валах и столбы насосных штанг. Вокруг шахты на 0 цепочка мастерских и холлов с дверями, цепь разомкнута на северо-западе, в шахту ведут четыре двери. Мостки на 0, −5 и над водой обвивают машину: на 0 крест над колёсами, на −5 центральный проход между колёсами и боковые отсеки за дверями. Спуск идёт маршем вдоль северной стены и маршем вдоль восточной через площадку −5. Лифт-клеть в юго-западном углу ходит с 0 на −9,75 без остановок, рычаги вызова на обоих концах, внизу он выходит на мостки. Центральные мостки над водой ведут на север к двойной двери насосной камеры с лучшей добычей.');
  const bot = r.level(BOT), mid = r.level(MID), g = r.level(0);
  g.carve(-16.8, -16.8, 16.8, 16.8).hole(-SX, -SZ, SX, SZ);
  mid.carve(-SX, -SZ, SX, SZ).hole(-SX, -SZ, SX, SZ);
  bot.carve(-SX, -SZ, SX, SZ);
  r.water(-SX, -SZ, SX, SZ, BOT);

  // Стены шахты с дверями на мостки.
  r.doorWall(-7.8, 8.7, 7.8, 8.7, [-5.2]);
  r.doorWall(-7.8, -8.7, 7.8, -8.7, [1]);
  r.doorWall(-7.5, -8.4, -7.5, 8.4, [3]);
  r.doorWall(7.5, -8.4, 7.5, 8.4, [-4]);
  // Цепочка комнат вокруг шахты, между северо-западными комнатами разрыв.
  r.doorWall(-4, 9, -4, 16.8, [13]);
  r.doorWall(6.6, 9, 6.6, 16.8, [12.4]);
  r.doorWall(6.6, 11, 16.8, 11, [12]);
  r.doorWall(7.8, 0.4, 16.8, 0.4, [14]);
  r.wall(7.5, -10.6, 7.5, -8.4);
  r.doorWall(4, -10.6, 16.8, -10.6, [15]);
  r.doorWall(4, -16.8, 4, -10.6, [-13]);
  r.doorWall(-6.6, -16.8, -6.6, -9, [-12.6]);
  r.doorWall(-16.8, -11, -6.6, -11, [-12]);
  r.doorWall(-16.8, 0.4, -7.8, 0.4, [-15]);
  r.wall(-16.8, 10, -7.8, 10);

  // Машина: колёса-топчаки, валы, опоры валов, насосные штанги.
  r.prop('Колесо-топчак', -3.2, 2.4, 2, 8, 8, { y: BOT });
  r.prop('Колесо-топчак', 3.2, -2.4, 2, 8, 8, { y: BOT });
  r.block(-4.6, 2.4, 5.2, 0.5, { y: -6.25, h: 0.5 });
  r.block(4.1, -2.4, 6.2, 0.5, { y: -6.25, h: 0.5 });
  for (const [x, z] of [[-1.7, 2.4], [-5.8, 2.4], [1.7, -2.4], [4.7, -2.4]]) r.column(x, z, { s: 0.6, y: BOT, h: 3.75 });
  for (const [x, z] of [[1.6, 3.4], [-1.6, -4.8], [-4.6, -4.6], [4.6, 3.2]]) r.column(x, z, { s: 0.5, y: BOT, h: 15.4, round: true });

  // Мостки на 0: запад, крест над колёсами, восток, юг, северная площадка над маршем.
  for (const a of [[-SX, 6.4, -3.2, SZ], [-SX, -5.4, -5.2, 6.4], [-5.2, -1, 5.2, 1], [5.2, -SZ, SX, SZ], [-4.2, -SZ, 5.2, -6.4], [3.2, 6.4, 5.2, SZ]]) r.slab(...a, 0);
  // Мостки на −5: площадка марша, проход между колёсами, запад, юг, восток.
  for (const a of [[3.2, 4.4, SX, SZ], [-1, 4.4, 3.2, 6.4], [-1, -6.4, 1, 4.4], [-SX, -4, -1, -2], [-SX, -2, -5.2, SZ], [-4.2, -SZ, SX, -6.4], [5.2, -6.4, SX, -2]]) r.slab(...a, MID);
  // Мостки над водой: от марша на юг и запад к лифту, по центру на север к насосной.
  for (const a of [[5.2, -SZ, SX, -2], [-4.2, -SZ, 5.2, -6.4], [-1, -6.4, 1, SZ]]) r.platform(...a, DECK, BOT);
  // Марши: вдоль северной стены с 0 на −5, вдоль восточной с −5 на мостки.
  r.stairs(0, 7.4, 2, 6.4, 5, 270, MID);
  r.stairs(6.2, 1.2, 2, 6.4, 4.75, 0, DECK);
  // Перила креста и внутренних краёв.
  for (const [x, z, w, d] of [[0, -1.1, 10.4, 0.14], [0, 1.1, 10.4, 0.14], [-5.1, -3.3, 0.14, 4.2], [-5.1, 3.7, 0.14, 5.4], [0.5, -6.3, 9.4, 0.14]]) r.prop('Парапет', x, z, w, d, 1);
  for (const [x, z, w, d] of [[-1.1, -5.2, 0.14, 2.4], [1.1, -2.9, 0.14, 6.6]]) r.prop('Парапет', x, z, w, d, 1, { y: MID });

  // Лифт-клеть: внизу выходит на южные мостки.
  r.lift(-5.7, 0, -6.9, 3, 3, DECK);
  r.lever(-3.4, 0, -8.3, 0, { action: 'lift' });
  r.lever(-3.4, DECK, -8.3, 0, { action: 'lift' });

  // Отсеки на −5 за дверями.
  mid.carve(-14, -3, -SX, 4).carve(SX, -8, 12.4, -3);
  r.doorWall(-7.5, -3, -7.5, 4, [0.5], { y: MID, h: 4.4 });
  r.doorWall(7.5, -8, 7.5, -3, [-4.8], { y: MID, h: 4.4 });
  r.prop('Полки с припасами', -13.6, 0.5, 0.7, 4, 2.2, { y: MID }); r.prop('Мешки', -10, 3.2, 1.6, 1, 0.8, { y: MID }); r.chest('LargeOakChest', -13, -2.2, { y: MID, ry: 45 });
  r.prop('Котёл', 11, -5.5, 1.6, 1.6, 1.2, { y: MID, round: true }); r.prop('Штабель ящиков', 11.4, -7.4, 1.4, 1, 2.2, { y: MID }); r.chest('SmallOakChest', 8.8, -7.4, { y: MID });

  // Насосная камера: шипы и маятники сгущаются к сундуку.
  bot.carve(-6, SZ, 6, 15.6).carve(-3, 15.6, 3, 16.8);
  r.doorWall(-6, 8.7, 6, 8.7, [0], { y: BOT, h: 4.4, double: true });
  r.block(-3.4, 12.2, 1.4, 1.4, { y: BOT, h: 4.4 }); r.block(3.4, 12.2, 1.4, 1.4, { y: BOT, h: 4.4 });
  r.prop('Котёл', -4.6, 14.6, 1.6, 1.6, 1.2, { y: BOT, round: true }); r.prop('Бочки', 4.8, 14.8, 1.4, 1.4, 1.2, { y: BOT });
  r.trap('Spike', 0, 10.4, { y: BOT }); r.trap('Blade', 0, 12.2, { y: BOT, ry: 0 }); r.trap('Spike', -1.2, 13.8, { y: BOT }); r.trap('Spike', 1.2, 13.8, { y: BOT }); r.trap('Vent', 0, 14.8, { y: BOT });
  r.chest('GoldenChest', 0, 16, { y: BOT, ry: 180 }); r.chest('GoldPile', -2, 15.9, { y: BOT }); r.chest('GoldPile', 2, 15.9, { y: BOT });
  r.trap('Spike', 0, 2, { y: DECK }); r.trap('Spike', 2, -7.4, { y: DECK });

  // Мастерские: станки, запасы.
  const stock = (x, z, w, d) => r.prop('Полки с припасами', x, z, w, d, 2.2);
  r.prop('Стол', -13, 14.4, 3, 1, 0.9); stock(-5, 12, 0.7, 4); r.chest('Crate', -15.8, 15.8);
  r.prop('Стол', 0, 11, 3, 1, 0.9); r.prop('Лавка', 0, 15.6, 3, 0.6, 0.5); r.prop('Бочки', 5.2, 15.4, 1.4, 1.4, 1.2);
  r.prop('Штабель ящиков', 14.8, 15, 1.6, 1.6, 2.2); r.prop('Мешки', 12, 15.8, 1.6, 1, 0.8);
  r.prop('Стол', 12, 3, 1, 3, 0.9); r.prop('Бочки', 8.8, 9.8, 1.4, 1.4, 1.2); r.chest('Barrel', 15.8, 1.6);
  stock(9.4, -6, 0.7, 4); r.prop('Лавка', 12, -2, 3, 0.6, 0.5); r.chest('SmallOakChest', 15.8, -1, { ry: 270 });
  r.prop('Штабель ящиков', 14.8, -15, 1.6, 1.6, 2.2); r.prop('Стол', 6, -15.2, 3, 1, 0.9);
  r.prop('Стол', -1, -12.4, 1, 3, 0.9); stock(-4, -15.8, 3, 0.7); r.chest('Crate', 3, -9.8);
  r.prop('Бочки', -15.4, -15.4, 1.4, 1.4, 1.2); r.prop('Мешки', -12, -15.8, 1.6, 1, 0.8);
  r.prop('Стол', -12, -4, 3, 1, 0.9); r.prop('Лавка', -9.8, -9.6, 3, 0.6, 0.5); r.chest('Crate', -15.8, -1);
  stock(-15.9, 4, 0.8, 4); r.prop('Бочки', -9, 8.6, 1.4, 1.4, 1.2);

  // Свет: мастерские почти без него, шахта светится снизу и с площадок.
  r.torch(-12, 16.4, 180); r.torch(16.4, 5, 270); r.torch(0, -16.4, 0); r.torch(-16.4, -5, 90);
  r.brazier(4.2, 7.6, MID); r.brazier(0, 7.6, DECK + 0.2); r.torch(-7, 7, 90); r.brazier(1.6, 14.8, BOT);

  r.monster('Sword', 12, 8, { ry: 180 }); r.monster('Sword', -11, 5, { ry: 0 }); r.monster('Crossbow', 0, 0, { ry: 90 });
  r.monster('Archer', 0, -3, { y: MID, ry: 90 }); r.monster('Warrior', 6.2, -5, { y: DECK, ry: 0 }); r.monster('Skull', 0, 11.8, { y: BOT });
  r.start(-12, 14, 90);
};
