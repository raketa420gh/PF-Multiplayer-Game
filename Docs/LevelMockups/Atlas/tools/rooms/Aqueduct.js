  r.block(8.5, -6.3, 1.4, 1.4, { h: 2.2 }); r.block(7.4, -9.4, 2.6, 1.4, { h: 1.3, ry: 25 }); r.block(5.2, -6.4, 1.8, 2.8, { h: 1.1, ry: 340 });
