// Правка: галереи в закрытых комнатах; секретный подземный этаж, открывается рычагами в правильном порядке; там много опасностей и куча золота.
exports.options = {};
exports.build = r => {
  r.desc('Зал 22 × 22 м с простенками и низкими брустверами; все проходы ведут в него короткими коридорами. На 5 м по периметру закрытые комнаты-галереи: из зала в них ведут только узкие бойницы, тело не пролезет, а вход только по лестницам за дверями у проходов (север, восток, запад). Северная, восточная и южная галереи соединены дверями, западная отдельная. Четыре рычага: на западной стене зала, в западной галерее, в тупике южной галереи и на восточной стене зала; верный порядок отодвигает плиту в южной стене зала. Лестница оттуда ведёт на подземный этаж: кольцо из лезвий, шипов, газа и стрелков вокруг золотой казны, в которую ведут два хода.');
  const pit = r.level(-6), g = r.level(0), up = r.level(5, 3.4);
  const H = 8.4;

  // Зал и коридоры от проходов.
  g.carve(-11, -11, 11, 11);
  for (const s of [-1, 1]) { g.carve(s * 8.4 - 1.2, 11, s * 8.4 + 1.2, 15).carve(s * 8.4 - 1.2, -15, s * 8.4 + 1.2, -11).carve(11, s * 8.4 - 1.2, 15, s * 8.4 + 1.2).carve(-15, s * 8.4 - 1.2, -11, s * 8.4 + 1.2); }
  up.carve(-11, -11, 11, 11).hole(-11, -11, 11, 11);

  // Простенки до потолка и брустверы.
  for (const [x, z, w, d] of [[-6, 6.5, 2, 2], [1.5, 7.5, 3, 2], [6.5, 3, 1.6, 3.4], [-2, 1.5, 3, 3], [-7.5, -2.5, 2.4, 2], [3.5, -3, 2, 2.6], [-2.5, -7.6, 3.4, 2], [7.5, -7.5, 2, 2]]) r.block(x, z, w, d, { h: H });
  for (const [x, z, w, d] of [[-9.4, 2.4, 2.2, 0.5], [-2, 4.8, 0.5, 2.6], [4.4, 1.4, 2.6, 0.5], [0.6, -9.4, 0.5, 2.4], [8.8, -2.6, 2.2, 0.5], [-5.8, -7.2, 2.6, 0.5]]) r.prop('Парапет', x, z, w, d, 1.3);
  r.prop('Обломки', 9, 7, 1.6, 1.4, 1, { ry: 25 });

  // Лестницы к галереям, каждая за дверью сбоку от прохода.
  g.carve(-7.2, 14.6, 0, 16.6); up.hole(-7.2, 14.6, 0, 16.8);
  r.stairs(-3.6, 15.6, 2, 7.2, 5, 90); r.door(-7.2, 15.6, 90);
  g.carve(14.6, 0, 16.6, 7.2); up.hole(14.6, 0, 16.8, 7.2);
  r.stairs(15.6, 3.6, 2, 7.2, 5, 180); r.door(15.6, 7.2, 0);
  g.carve(-16.6, -7.2, -14.6, 0); up.hole(-16.8, -7.2, -14.6, 0);
  r.stairs(-15.6, -3.6, 2, 7.2, 5, 0); r.door(-15.6, -7.2, 0);

  // Галереи: закрытые комнаты в скале, в зал смотрят только бойницы.
  up.carve(-14.6, 12, 11.4, 16.8).carve(12, -11.4, 16.8, 16.8).carve(-14.6, -16.8, 11.4, -12).carve(-16.8, -9, -12, 11);
  up.carve(12, -16.8, 16.8, -11.4);
  for (const x of [-9, -5, 1, 7]) up.carve(x - 0.25, 11, x + 0.25, 12);
  for (const x of [-7, -2, 3, 8]) up.carve(x - 0.25, -12, x + 0.25, -11);
  for (const z of [-8, -3, 2, 7.5]) up.carve(11, z - 0.25, 12, z + 0.25);
  for (const z of [-5, 1, 6]) up.carve(-12, z - 0.25, -11, z + 0.25);
  // Двери между галереями.
  for (const z of [14, -14]) { up.carve(11.4, z - 1, 12, z + 1); r.door(11.7, z, 90, { y: 5 }); r.block(11.7, z, 0.6, 2, { y: 7.4, h: 1 }); }

  // Рычаги: два в зале, два в разных крыльях галерей.
  r.lever(-10.9, 0, -5, 90, { order: 1 });
  r.lever(-16.7, 5, 6, 90, { order: 2 });
  r.lever(-14.5, 5, -14, 90, { order: 3 });
  r.lever(10.9, 0, -5, 270, { order: 4 });

  r.torch(-10.6, 0, 90); r.torch(10.6, 0, 270); r.brazier(1.6, -0.6);
  r.torch(14, 16.4, 180, 5); r.torch(-13, -16.4, 0, 5); r.candle(-14, 8, 5);
  r.monster('Archer', -1, 13, { y: 5, ry: 180 }); r.monster('Archer', 13.2, -2, { y: 5, ry: 270 }); r.monster('Crossbow', 3, -13.2, { y: 5 }); r.monster('Archer', -13.2, 3, { y: 5, ry: 90 });
  r.monster('Sword', -4.6, -4, { ry: 90 }); r.monster('Warrior', 4.6, 6.6, { ry: 200 });
  r.chest('SmallOakChest', -15.4, 10, { y: 5, ry: 90 }); r.chest('LargeOakChest', 15.6, 15.6, { y: 5, ry: 180 }); r.chest('Crate', 9.6, 9.8);
  r.start(-8.4, 13, 180);

  // Вход в секрет: плита в южной стене зала уезжает на восток в толщу скалы.
  g.carve(-3.4, -14.4, -0.8, -11).carve(-0.8, -14.4, 6.4, -12);
  r.secretDoor(-2.1, 0, -11.3, 2.6, 2.8, 0.6, [2.7, 0, 0]);
  r.stairs(2.8, -13.2, 2.4, 7.2, 6, 270, -6); g.hole(-0.8, -14.4, 6.4, -12);

  // Подземный этаж: кольцо вокруг казны.
  pit.carve(-14, -14.4, 14, -10.4).carve(-14, -14.4, -10.6, 14).carve(-14, 10.6, 14, 14).carve(10.6, -14.4, 14, 14);
  pit.carve(-7, -7, 7, 7).carve(-1.2, 7, 1.2, 10.6).carve(-10.6, -3, -7, -0.6);
  // Южное плечо: маятники.
  for (const x of [-4, -7.5]) r.trap('Blade', x, -12.4, { y: -6, ry: 90 });
  r.chest('GoldPile', -5.8, -13.6, { y: -6 });
  // Западное плечо: шахматные шипы и столбы.
  for (const [x, z] of [[-13, -9], [-11.6, -7], [-13, 3], [-11.6, 5], [-13, 7]]) r.trap('Spike', x, z, { y: -6 });
  r.column(-13.4, 0, { s: 1.2, y: -6, h: 5.4 });
  r.chest('GoldPile', -13.2, 12.8, { y: -6 }); r.chest('GoldPile', -11.6, -13.2, { y: -6 });
  // Северное плечо: газ и стрелок за брусвером.
  for (const x of [-8, -3.4, 5]) r.trap('Vent', x, 12.3, { y: -6 });
  r.prop('Парапет', 9.4, 13.3, 0.5, 1.4, 1.3, { y: -6 }); r.monster('Crossbow', 11.4, 12.6, { y: -6, ry: 270 });
  r.chest('GoldPile', 2.6, 13.2, { y: -6 });
  // Восточное плечо: глухое, лезвия и засада.
  for (const z of [4, -3]) r.trap('Blade', 12.3, z, { y: -6, ry: 0 });
  r.monster('Sword', 12.6, -10, { y: -6 }); r.monster('Sword', 12, 8.4, { y: -6, ry: 180 });
  r.chest('GoldPile', 13.2, 0.6, { y: -6 });
  // Казна.
  r.platform(-3, -3, 3, 3, -5.75, -6);
  r.chest('GoldenChest', 0, 1.4, { y: -5.75 }); r.chest('GoldenChest', -1.6, -1, { y: -5.75, ry: 90 });
  for (const [x, z] of [[1.6, -1.2], [-4.6, 4.6], [4.8, 4.8], [4.8, -4.4], [-4.6, -5], [0.4, 5.2], [5.2, 0], [-5.2, 1.6], [0, -5.2]]) r.chest('GoldPile', x, z, { y: -6 });
  r.monster('Mage', 0, -1.2, { y: -5.75 }); r.monster('Warrior', 0, 8.4, { y: -6, ry: 0 });
  for (const [x, z] of [[-6, -6], [6, -6], [-6, 6], [6, 6]]) r.trap('Spike', x, z, { y: -6 });
  r.brazier(6.2, 2.6, -6); r.torch(-13.6, 1, 90, -6);
};
