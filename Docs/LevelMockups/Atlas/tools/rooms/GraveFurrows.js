// Новая: посевное поле, шесть параллельных окопов-борозд с гробами, межи уступами вниз на восток, вышка сеятеля посередине.
const BASE = -5, FX = 13, FZ = 12.4, DEPTH = 2;
// Межи с запада на восток: x1, x2, верх. Поле падает тремя шагами по 1,25.
const BERMS = [[-13, -11.2, 1.25], [-9, -7.2, 1.25], [-5, -3.2, 0], [-1, 1, 0], [3.2, 5, -1.25], [7.2, 9, -1.25], [11.2, 13, -2.5]];
// Борозды: x1, x2, верх восточной межи, засыпанные участки (z1, z2) и марши (z низа, z верха).
const FURROWS = [
  [-11.2, -9, 1.25, [[3, 5], [-12.4, -9]], [[7.6, 5], [-6.4, -9]]],
  [-7.2, -5, 0, [[7, 12.4], [-3, -1]], [[4.4, 7], [-5.6, -3]]],
  [-3.2, -1, 0, [[5, 7], [-12.4, -6]], [[9.6, 7], [2.4, 5]]],
  [1, 3.2, -1.25, [[9, 12.4], [-12.4, -6]], [[6.4, 9], [-3.4, -6]]],
  [5, 7.2, -1.25, [[2, 4], [-12.4, -9]], [[6.6, 4], [-0.6, 2]]],
  [9, 11.2, -2.5, [[6, 12.4], [-6, -4]], [[3.4, 6], [-8.6, -6]]],
];

exports.options = {};
exports.build = r => {
  r.desc('Почти весь пол прорезан шестью параллельными бороздами шириной 2,2 и глубиной 2 м с рядами гробов и костей, между ними идут узкие межи. Поле падает с запада на восток тремя уступами по 1,25, от +1,25 до −2,5, поэтому западные проёмы входят на него маршем вверх, а восточные спускаются тамбуром в обратную сторону. Межи связаны перемычками, поверху быстро, но видно с вышки сеятеля +3,5 на столбах над двумя средними бороздами. У каждой борозды два входа-марша, её рвут перемычки, завалы и шипы, почти каждый участок кончается тупиком. Лучшая добыча лежит на дне самой глубокой восточной борозды, −4,5, за рядом шипов. Все восемь проёмов прикрыты сторожками с дверью на поле.');
  const low = r.level(BASE), g = r.level(0, 7);
  low.carve(-FX, -FZ, FX, FZ); g.carve(-FX, -FZ, FX, FZ); g.hole(-FX, -FZ, FX, FZ);
  const bank = (x1, z1, x2, z2, top, y0 = BASE) => r.platform(x1, z1, x2, z2, top, y0);

  // Межи и борозды.
  for (const [x1, x2, top] of BERMS) bank(x1, -FZ, x2, FZ, top);
  for (const [x1, x2, top, dams, flights] of FURROWS) {
    const floor = top - DEPTH, xc = (x1 + x2) / 2;
    if (floor > BASE) bank(x1, -FZ, x2, FZ, floor);
    for (const [z1, z2] of dams) bank(x1, z1, x2, z2, top, floor);
    for (const [zLow, zTop] of flights) r.stairs(xc, (zLow + zTop) / 2, x2 - x1, Math.abs(zTop - zLow), DEPTH, zTop > zLow ? 0 : 180, floor);
  }
  // Переходы вниз по уступу: марш поперёк засыпанного участка, 1,25 на запад вверх.
  for (const [x, z, y] of [[-6.4, 8, 0], [-6.4, -2, 0], [1.8, 10.4, -1.25], [1.8, -7, -1.25], [9.8, 7.4, -2.5], [9.8, -5, -2.5]]) r.stairs(x, z, 2, 1.6, 1.25, 270, y);

  // Сторожки запада: с порога марш вверх на крайнюю межу, дверь на +1,25.
  const westHut = (z1, z2, door) => {
    g.carve(-16.8, z1, -FX, z2);
    r.wall(-13.3, z1, -13.3, z2, { h: 1.25 });
    r.doorWall(-13.3, z1, -13.3, z2, [door], { y: 1.25, h: 5.75 });
    r.stairs(-14.6, door, 2, 1.6, 1.25, 90);
    r.platform(-13.8, door - 1, -13, door + 1, 1.25);
  };
  westHut(5.4, 11.2, 6.8); westHut(-11.4, -5.6, -10.2);

  // Сторожки севера и юга над западной половиной: марш вдоль стены к площадке +1,25.
  const midHut = (x1, x2, zSign, stairX, ry) => {
    const zIn = zSign * FZ, zWall = zSign * 12.7, zFar = zSign * 16.8;
    g.carve(x1, zIn, x2, zFar);
    r.wall(x1, zWall, x2, zWall, { h: 1.25 });
    r.doorWall(x1, zWall, x2, zWall, [-8.1], { y: 1.25, h: 5.75 });
    r.stairs(stairX, zSign * 14, 2, 1.6, 1.25, ry);
  };
  midHut(-9.6, -4, 1, -6.2, 270); r.platform(-9.4, 12.4, -7, 15, 1.25);
  midHut(-12.4, -7, -1, -10, 90); r.platform(-9.2, -15, -7, -12.4, 1.25);

  // Сторожки севера и юга над восточной половиной: тамбур с изломом, дверь на 0, за ней марш вниз на межу −1,25.
  g.carve(5, FZ, 11.6, 16.8);
  r.doorWall(5, 12.7, 11.6, 12.7, [8.1], { h: 7 });
  r.wall(7, 14.9, 11.6, 14.9, { h: 3.2 });
  r.stairs(8.1, 11.6, 1.8, 1.6, 1.25, 0, -1.25);
  g.carve(5.2, -16.8, 12, -FZ);
  r.doorWall(5.2, -12.7, 12, -12.7, [8.1], { h: 7 });
  r.wall(5.2, -14.9, 10, -14.9, { h: 3.2 });
  r.stairs(8.1, -11.6, 1.8, 1.6, 1.25, 180, -1.25);

  // Сторожки востока: с порога вдоль стены и назад маршем вниз, дверь на −2,5 на последнюю межу.
  const eastHut = (s, door) => {
    const zA = s * 4.2, zB = s * 9.6, zFar = s * 11.4;
    low.carve(FX, zA, 15.4, zB); g.carve(FX, zA, 15.4, zFar); g.carve(15.4, s * 7.2, 16.8, zFar); g.hole(FX, zA, 15.4, zB);
    r.wall(13.3, zA, 13.3, zB, { y: BASE, h: 2.5 });
    r.doorWall(13.3, zA, 13.3, zFar, [door], { y: -2.5, h: 9.5 });
    r.platform(FX, zA, 15.4, s * 6.4, -2.5, BASE);
    r.stairs(14.5, s * 8, 1.8, 3.2, 2.5, s > 0 ? 0 : 180, -2.5);
  };
  eastHut(1, 5.3); eastHut(-1, -5.3);

  // Вышка сеятеля: над двумя средними бороздами, столбы на межах, марш по центральной меже.
  r.slab(-3.8, -0.5, 3.8, 3.5, 3.5);
  for (const [x, z, y] of [[-3.5, -0.2, 0], [-3.5, 3.2, 0], [3.5, -0.2, -1.25], [3.5, 3.2, -1.25]]) r.column(x, z, { s: 0.6, y, h: 3.5 - 0.6 - y });
  r.stairs(0, -2.6, 2, 4.2, 3.5, 0);
  for (const [x, z, w, d] of [[-3.65, 1.5, 0.3, 4], [3.65, 1.5, 0.3, 4], [0, 3.35, 7.6, 0.3], [-2.4, -0.35, 2.8, 0.3], [2.4, -0.35, 2.8, 0.3]]) r.prop('Парапет', x, z, w, d, 1, { y: 3.5 });

  // Свод: со стороны запада и востока потолок ниже, вершина над вышкой.
  r.block(-11, 0, 4, 24.8, { y: 5.6, h: 1.4 });
  r.block(11, 0, 4, 24.8, { y: 5.6, h: 1.4 });

  // Посев: гробы вдоль западной стенки борозды, кости на дне.
  const row = (x1, floor, zs) => zs.forEach((z, i) => { r.prop('Гроб', x1 + 0.4, z, 0.7, 1.9, 0.6, { y: floor }); if (i % 2 === 0) r.prop('Кости', x1 + 1.6, z + 1, 1, 1.2, 0.2, { y: floor }); });
  row(-11.2, -0.75, [9.4, 1.5, -1.5, -4.5]);
  row(-7.2, -2, [2.8, 0.4, -7.2]);
  row(-3.2, -2, [11.4, 0.8, -2.2]);
  row(1, -3.25, [4.8, -1.4]);
  row(5, -3.25, [8, 11, -2, -5, -7.6]);
  row(9, -4.5, [1.8, -2.4, -11.2]);

  // Завалы рвут борозды на тупики.
  r.prop('Обломки', 2.1, 1.5, 2.2, 1.8, 1.3, { y: -3.25 });
  r.prop('Обломки', -6.1, -11.4, 2.2, 1.6, 1.2, { y: -2 });
  r.prop('Обломки', -2.1, -5, 2.2, 1.6, 1.2, { y: -2 });
  r.prop('Обломки', 6.1, -5.8, 1.1, 1.6, 1, { y: -3.25, ry: 8 });
  r.prop('Обломки', -10.1, -2.8, 1, 1.6, 1, { y: -0.75, ry: 350 });
  r.prop('Обломки', 4.1, -8, 1.2, 1.4, 0.9, { y: -1.25, ry: 20 });
  r.prop('Обломки', -8.1, 2, 1.2, 1.2, 0.9, { y: 1.25, ry: 340 });

  // Шипы: от западных борозд к восточной всё гуще.
  r.trap('Spike', -9.7, 0, { y: -0.75 });
  r.trap('Spike', -5.7, -7, { y: -2 });
  r.trap('Spike', 2.6, 4, { y: -3.25 });
  r.trap('Spike', 6.6, -3.8, { y: -3.25 });
  r.trap('Spike', 5.6, 9.6, { y: -3.25 });
  r.trap('Spike', 9.6, 2.6, { y: -4.5 });
  r.trap('Spike', 10.5, 0.6, { y: -4.5 });
  r.trap('Spike', 9.6, -0.6, { y: -4.5 });
  r.trap('Spike', 10.5, -1.6, { y: -4.5 });

  // Добыча: чем восточнее и глубже, тем лучше.
  r.chest('GoldenChest', 10.1, -3.4, { y: -4.5, ry: 0 });
  r.chest('Coffin', 9.6, -9.6, { y: -4.5, ry: 90 });
  r.chest('LargeOakChest', 6.1, 12, { y: -3.25, ry: 180 });
  r.chest('Coffin', 2, -0.4, { y: -3.25, ry: 270 });
  r.chest('SmallOakChest', -2.1, 11.9, { y: -2, ry: 180 });
  r.chest('Coffin', -6.1, -9.8, { y: -2, ry: 0 });
  r.chest('Urn', -10.1, 12, { y: -0.75 });
  r.chest('SmallOakChest', 1.8, 2.6, { y: 3.5, ry: 180 });

  // Обстановка сторожек.
  r.prop('Лавка', -15.8, 10.4, 0.5, 1.4, 0.45);
  r.prop('Стол', -14.8, -6.8, 1.4, 0.8, 0.8);
  r.prop('Мешки', -12, -13.2, 1, 1.4, 0.8);
  r.prop('Лавка', 9.8, 13.3, 1.6, 0.5, 0.45);
  r.prop('Бочки', 5.8, -13.2, 1, 1, 1);
  r.chest('Crate', 11, 13.4);
  r.chest('Crate', -15.9, 6.4);

  // Свет: сторожки горят, в бороздах темно.
  r.torch(-16.5, 6.4, 90);
  r.torch(-16.5, -6.4, 90);
  r.torch(16.5, 10.6, 270);
  r.torch(16.5, -10.6, 270);
  r.brazier(0, 1.5, 3.5);
  r.brazier(-8.1, -7.2, 1.25);
  r.brazier(8.1, 0.4, -1.25);
  r.candle(9.4, -3, -4.5);

  r.monster('Crossbow', -1.8, 1.8, { y: 3.5, ry: 90 });
  r.monster('Sword', -8.1, 5.6, { y: 1.25, ry: 90 });
  r.monster('Skull', 2, -2.2, { y: -3.25, ry: 90 });
  r.monster('Sword', 4.1, 6, { y: -1.25, ry: 270 });
  r.monster('Warrior', 10, -3, { y: -4.5, ry: 0 });
  r.start(-8.4, 15.8, 180);
};
