// Правка: центр оставить, снаружи сложные коридоры-комнаты с деревянными дверями между ними.
exports.options = {};
exports.build = r => {
  r.desc('В центре прежний круг: руна, кольцо из 8 свечей, жертвенник с сундуком, маг и черепа; факелов нет, всё вокруг во тьме. Круг заперт в ступенчатом зале с четырьмя дверями. Снаружи два слоя: внутренний обходной коридор разбит глухими стенами и дверями на восемь колен, внешний ряд из одиннадцати комнат принимает проёмы. Кратчайшего пути по кольцу нет: к кругу попадают только из четырёх колен, и в них приходится идти через комнаты.');
  const g = r.level(0);
  g.carve(-16.8, -16.8, 16.8, 16.8);
  const D = (x1, z1, x2, z2, at, o) => r.doorWall(x1, z1, x2, z2, at, o);
  // Центр: зал со ступенчатыми углами вокруг круга.
  D(-9.5, 9.5, 9.5, 9.5, [-2], { double: true }); D(-9.5, -9.5, 9.5, -9.5, [3], { double: true }); D(-9.5, -9.2, -9.5, 9.2, [4]); D(9.5, -9.2, 9.5, 9.2, [-3]);
  for (const [x, z] of [[1, 1], [-1, 1], [1, -1], [-1, -1]]) r.block(x * 7.85, z * 7.85, 2.7, 2.7);
  r.add('fx', 'Rune', [0, 0.02, 0], [13.12, 0, 13.12], {});
  for (let i = 0; i < 8; i++) r.candle(5.5 * Math.sin(i * Math.PI / 4), 5.5 * Math.cos(i * Math.PI / 4));
  r.prop('Алтарь', 0, 0, 2.4, 1.2, 0.9);
  r.chest('LargeOakChest', 0, 2.2, { ry: 180 });
  r.monster('Mage', 0, -2.4); r.monster('Skull', 4, 4, { ry: 225 }); r.monster('Skull', -4, -4, { ry: 45 });

  // Стена между коридором и внешними комнатами.
  D(-12.8, 12.5, 12.8, 12.5, [-10, -1, 10]);
  D(-12.8, -12.5, 12.8, -12.5, [-8, -1, 4]);
  D(12.5, -12.2, 12.5, 12.2, [9, 3, -9]);
  D(-12.5, -12.2, -12.5, 12.2, [10, 0, -5]);
  // Коридор рвётся на восемь колен: двери и глухие стены вперемежку.
  D(3, 9.8, 3, 12.2, [11]); r.wall(-7, 9.8, -7, 12.2);
  D(9.8, 6, 12.2, 6, [11]); r.wall(9.8, -6, 12.2, -6);
  D(-3, -12.2, -3, -9.8, [-11]); r.wall(7, -12.2, 7, -9.8);
  D(-12.2, -7, -9.8, -7, [-11]); r.wall(-12.2, 7, -9.8, 7);
  // Внешние комнаты, двери между ними у внешней стены.
  for (const x of [-4.5, 4.5]) D(x, 12.8, x, 16.8, [14.8]);
  for (const x of [-5, 2]) D(x, -16.8, x, -12.8, [-14.8]);
  D(12.8, 0, 16.8, 0, [14.8]);
  for (const z of [-3, 3]) D(-16.8, z, -12.8, z, [-14.8]);
  // Углы вертушкой: каждый угол принадлежит одной из двух соседних комнат.
  D(12.8, 12.5, 16.8, 12.5, [14.8]); D(12.8, -12.5, 16.8, -12.5, [14.8]); D(-16.8, -12.5, -12.8, -12.5, [-14.8]); D(-16.8, 12.5, -12.8, 12.5, [-14.8]);

  // Комнаты: немного ритуального хлама и укрытия.
  r.prop('Саркофаг', 0, 15.6, 2.4, 1.1, 1); r.prop('Кости', -0.5, 13.6, 1.2, 1.2, 0.2);
  r.prop('Полки с припасами', -13, 16.3, 2.6, 0.6, 2.2); r.chest('SmallOakChest', -6.7, 13.4, { ry: 0 });
  r.prop('Обломки', 7.4, 13.6, 2, 1.2, 1); r.chest('Urn', 15.9, 15.9);
  r.prop('Черепа', 15.8, 5, 0.9, 0.9, 0.5); r.prop('Скамья', 15.8, 2, 2, 0.6, 0.5);
  r.prop('Гроб', 15.4, -4, 1, 2.3, 0.7); r.chest('Bookshelf', 16.3, -11, { ry: 270 });
  r.prop('Кости', 8, -15.6, 1.2, 1.2, 0.2); r.prop('Обломки', 14.2, -15.4, 1.2, 1.8, 1);
  r.prop('Алтарь', -1.5, -15.7, 1.8, 0.9, 0.9); r.chest('Urn', 0.6, -13.25);
  r.prop('Скамья', -14.5, 0, 0.6, 2, 0.5); r.chest('SmallOakChest', -16, 0, { ry: 90 });
  r.prop('Гроб', -16.2, -6, 1, 2.3, 0.7); r.prop('Полки с припасами', -13.3, 6, 0.6, 2.6, 2.2);
  // Колена коридора: завалы в середине не перекрывают проход.
  r.prop('Кости', -4, 11, 1.2, 1.2, 0.2); r.prop('Обломки', 11, 1, 1.2, 1, 1); r.prop('Обломки', 5.9, -11.4, 1.6, 0.8, 1);
  r.monster('Sword', -13.5, 4, { ry: 90 }); r.monster('Sword', 13.5, -4, { ry: 270 }); r.monster('Skull', 6, 11, { ry: 270 });
  r.start(-14.5, -14.5, 45);
};
