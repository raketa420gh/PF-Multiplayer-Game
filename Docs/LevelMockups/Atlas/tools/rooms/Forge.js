// Новая: пустотелый горн-башня от зольника до загрузочной галереи, сквозь зал наковален идёт шлаковая траншея.
const TOP = 5, ASH = -5, SLAG = -1.25, H = 4.4;

exports.options = {};
exports.build = r => {
  r.desc('Посреди клетки стоит пустотелая башня горна 9,6 × 9,6 м с четырьмя зарешеченными устьями: низ обходится кольцом, внутрь снизу не попасть. К югу зал наковален в два яруса высотой, через него с запада на восток и затем на север идёт шлаковая траншея −1,25, разрезанная двумя мостками на три участка, у каждого свой спуск. Два марша, западный и восточный, поднимаются на загрузочную галерею +5 с вагонетками и рудным закромом; в центре галереи загрузочный зев, рядом с ним марш внутрь башни. Через площадку на 0 второй марш уходит в низкий зольник −5, огненные решётки к нему всё чаще, в дальнем углу золотой сундук. Из зольника ход идёт под коленом траншеи к лестнице в северо-восточную мастерскую.');
  const ash = r.level(ASH), slag = r.level(SLAG), g = r.level(0), up = r.level(TOP, 5.4);

  // Низ: южная половина, кольцо вокруг башни, западный карман, восток, мастерские.
  g.carve(-16.8, -16.8, 16.8, -4.4);
  g.carve(-16.8, -4.4, -13, -2).carve(13.4, -4.4, 16.8, -2);
  g.carve(-9.5, -4.4, 7, 10.7);
  g.carve(-13, -4.4, -9.5, 6.6);
  g.carve(7, -4.4, 13.4, 10.4);
  g.carve(13.4, 5.6, 16.8, 10.4);
  g.carve(-16.8, 7.2, -10, 16.8).carve(-16.8, 10.7, -1.5, 16.8);
  g.carve(1.5, 10.7, 16.8, 16.8);

  // Тамбуры: южные проёмы и нижние боковые проёмы в L-образных сенях, в зал только через двери.
  r.block(0, -15.1, 6, 3.4, { h: H });
  r.doorWall(-13, -13.5, 0, -13.5, [-5], { h: H });
  r.doorWall(0, -13.5, 13.4, -13.5, [6], { h: H, double: true });
  r.doorWall(-13, -13.5, -13, -2, [-11], { h: H });
  r.doorWall(13.4, -13.5, 13.4, -2, [-11], { h: H });
  r.doorWall(13.4, 5.6, 13.4, 7.8, [6.7], { h: H });
  r.doorWall(-10, 10.7, -1.5, 10.7, [-6], { h: H });
  r.doorWall(1.5, 10.7, 16.8, 10.7, [3.2, 15], { h: H });
  r.block(-12.4, 12.4, 2.6, 2.6, { h: H });

  // Башня горна: четыре устья, в каждом решётка.
  const mouth = { door: false, h: H };
  r.doorWall(-5.8, -1.5, 3.8, -1.5, [-1], mouth);
  r.doorWall(-5.8, 7.5, 3.8, 7.5, [-1], mouth);
  r.doorWall(-5.5, -1.2, -5.5, 7.2, [3], mouth);
  r.doorWall(3.5, -1.2, 3.5, 7.2, [3], mouth);
  r.bars(-2, -1.5, 0, -1.5); r.bars(-2, 7.5, 0, 7.5); r.bars(-5.5, 2, -5.5, 4); r.bars(3.5, 2, 3.5, 4);
  // Внутри: зев, марш с галереи на площадку 0, марш с площадки в зольник.
  g.hole(-5.2, 0.8, 3.2, 7.2);
  slag.carve(-5.2, 0.8, 3.2, 7.2).hole(-5.2, 0.8, 3.2, 7.2);
  r.stairs(-4.2, 4, 2, 6.4, TOP, 0, 0);
  r.stairs(2.2, 4, 2, 6.4, 5, 180, ASH);

  // Траншея: мостки на x −5,3 и 2,5, колено на север вдоль восточного прохода.
  for (const t of [[-11, -6.6, -6.4, -4.4], [-4.2, -6.6, 1.4, -4.4], [3.6, -6.6, 9.2, -4.4], [7, -4.4, 9.2, 4.6]]) { slag.carve(...t); g.hole(...t); }
  r.stairs(-10.1, -5.5, 2.2, 1.8, 1.25, 270, SLAG);
  r.stairs(0.5, -5.5, 2.2, 1.8, 1.25, 90, SLAG);
  r.stairs(8.1, 3.7, 2.2, 1.8, 1.25, 0, SLAG);
  for (const x of [-6.5, -4.1, 3.7]) r.prop('Парапет', x, -5.5, 0.2, 2.2, 1);

  // Галерея: крыша башни с проходами, западная площадка, рудный закром.
  up.carve(-9.5, -3.8, 7, 10.4).carve(-12.7, -3.8, -9.5, 6.6).carve(7, -3.8, 13.1, 10.4).carve(-12.7, -13.2, 13.1, -3.8);
  up.carve(-7, 10.4, 3, 15.4);
  up.hole(-5.2, 0.8, 1.2, 7.2);
  up.hole(-12.7, -13.2, 13.1, -3.8).hole(7, -3.8, 13.1, 10.4).hole(-12.7, -3.8, -9.5, 4.2);
  r.stairs(-11.2, 1, 2.4, 6.4, TOP, 0, 0);
  r.stairs(10.2, 9.1, 2.6, 6.4, TOP, 270, 0);
  r.doorWall(-7, 10.7, 3, 10.7, [-2], { y: TOP, h: 5.4 });
  for (const [x, z, w, d] of [[-1, -3.65, 17, 0.3], [-9.35, 0.2, 0.3, 8], [6.85, 2, 0.3, 11.6], [1.35, 4, 0.3, 6.4], [-2, 0.65, 6.6, 0.3], [-1, 7.35, 4.4, 0.3], [-11.1, 4.35, 3.2, 0.3]]) r.prop('Парапет', x, z, w, d, 1, { y: TOP });

  // Зольник и ход под коленом траншеи к лестнице в мастерскую.
  ash.carve(-9, -3, 5.4, 9.6);
  ash.carve(5.4, 1.4, 13.6, 3.4).carve(11.6, 1.4, 13.6, 13.4).carve(5.2, 11, 11.6, 13.4);
  slag.carve(5.2, 11, 11.6, 13.4).hole(5.2, 11, 11.6, 13.4);
  g.hole(5.2, 11, 11.6, 13.4);
  r.stairs(8.4, 12.2, 2.4, 6.4, 5, 270, ASH);
  for (const [x, z, w, d] of [[8.4, 13.55, 6.4, 0.3], [11.75, 12.2, 0.3, 3]]) r.prop('Парапет', x, z, w, d, 1);
  for (const [x, z, s] of [[-5.6, 0.6, 1.6], [-6.4, 6, 1.4], [-2.4, 8.6, 1.2], [0, -1.8, 1.4]]) r.column(x, z, { s, y: ASH, h: 3.15 });
  r.block(-8.8, 3.8, 2.6, 0.8, { y: ASH, h: 3.15 });

  // Зал наковален: ряды, бочки с водой, вторая линия укрытий.
  for (const x of [-11, -7, -3, 1, 5, 9]) r.prop('Наковальня', x, -8.6, 1.2, 0.6, 0.9, { ry: x % 4 ? 0 : 10 });
  for (const x of [-9.6, -1.4, 6.6]) r.prop('Наковальня', x, -11.4, 1.2, 0.6, 0.9);
  for (const [x, z] of [[-5, -11.4], [2.4, -11.6], [10.8, -11.2], [-11.4, -12]]) r.prop('Бочки', x, z, 1.4, 1.4, 1.2);
  r.prop('Очаг', -4.8, -8.6, 1.4, 1.4, 0.9);
  r.prop('Очаг', 3, -8.8, 1.4, 1.4, 0.9);
  r.prop('Обломки', 10.6, 0.6, 2.4, 1.6, 1.1, { ry: 15 });
  r.prop('Штабель ящиков', 12.2, -2.4, 1.4, 1.4, 2.2);
  r.prop('Кости', -1.4, -5.4, 1.4, 1, 0.2, { y: SLAG });
  r.prop('Обломки', 4.6, -5.5, 1.4, 1.2, 0.9, { y: SLAG });
  r.chest('Urn', -7, -5.5, { y: SLAG });
  r.chest('SmallOakChest', -3.4, -5.5, { y: SLAG, ry: 90 });
  r.chest('Barrel', -15.8, -3); r.chest('Crate', 15.8, -3);
  r.trap('Spike', -2, -5.6, { y: SLAG }); r.trap('Spike', 8, 0.4, { y: SLAG });

  // Мастерские.
  r.prop('Стол', -6, 15.4, 3, 1, 0.9); r.prop('Стойка с оружием', -3, 13.6, 0.6, 2.4, 1.8); r.prop('Полки с припасами', -15.9, 13, 0.8, 4, 2.2); r.prop('Бочки', -11, 8.4, 1.4, 1.4, 1.2);
  r.prop('Стол', 13.5, 13.4, 1, 3, 0.9); r.prop('Наковальня', 3.4, 15, 1.2, 0.6, 0.9); r.prop('Штабель ящиков', 15.6, 11.8, 1.6, 1.6, 2.2);
  r.chest('LargeOakChest', -15.8, 15.8, { ry: 135 }); r.chest('Crate', 2.4, 15.9);

  // Галерея и закром: вагонетки вдоль южного края, руда у зева.
  r.prop('Рудная вагонетка', 3.8, -2.6, 2, 1.2, 1.2, { y: TOP, ry: 90 });
  r.prop('Рудная вагонетка', -7.6, 8.8, 2, 1.2, 1.2, { y: TOP });
  r.prop('Рудная вагонетка', 2.8, 9.6, 2, 1.2, 1.2, { y: TOP, ry: 20 });
  r.prop('Обломки', -6.8, -1.6, 1.8, 1.4, 0.8, { y: TOP, ry: 30 });
  r.prop('Рудная вагонетка', 1, 14, 2, 1.2, 1.2, { y: TOP });
  r.prop('Обломки', -5.4, 13.6, 2.4, 2.4, 1.2, { y: TOP, ry: 10 });
  r.chest('LargeOakChest', -1.6, 14.6, { y: TOP, ry: 180 });

  // Огненные решётки: чем ниже, тем чаще; золотой сундук в дальнем углу зольника.
  r.trap('Vent', -3, -0.2);
  r.trap('Vent', 1, -0.2);
  r.trap('Vent', 2.2, 3, { y: -1.9 });
  r.trap('Vent', 2.2, 5.6, { y: -4 });
  for (const [x, z] of [[1.6, 8.4], [-1, 4.6], [-3.6, 7.4], [-4.2, 2.4], [-1, 0.4], [-7.6, 8], [-7, 2], [-7.8, 5.6]]) r.trap('Vent', x, z, { y: ASH });
  r.chest('GoldenChest', -8, 8.6, { y: ASH, ry: 135 });
  r.chest('GoldPile', -8.2, 7, { y: ASH });
  r.chest('LargeOakChest', 4.4, -2, { y: ASH, ry: 0 });
  r.chest('Urn', 12.6, 12.6, { y: ASH });
  r.prop('Кости', 9, 2.4, 1.6, 1, 0.2, { y: ASH });

  // Свет: угли в устьях и зольнике, факелы в зале и мастерских.
  r.brazier(-1, -0.2); r.brazier(-1, 3, ASH); r.brazier(-7.8, 7.4, ASH);
  r.torch(-1, -13.2, 0); r.torch(-12.6, 1, 90);
  r.torch(-1.8, 13.6, 270); r.torch(16.4, 14, 270);
  r.brazier(-8.4, 8.4, TOP);

  r.monster('Sword', -9, -10, { ry: 90 }); r.monster('Warrior', 3, -10, { ry: 0 });
  r.monster('Archer', -3, -2.8, { y: TOP, ry: 180 });
  r.monster('Sword', 13, 13.5, { ry: 270 });
  r.monster('Mage', -2, 4, { y: ASH, ry: 0 });
  r.monster('Skull', 12.6, 6, { y: ASH, ry: 180 });
  r.start(-14.8, 9, 90);
};
