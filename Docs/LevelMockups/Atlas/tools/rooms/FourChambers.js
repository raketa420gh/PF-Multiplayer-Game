// Правка: в комнатах проёмы с дверями, такими же как между модулями; секретная комната снизу, попасть на лифте.
exports.options = {};
exports.build = r => {
  r.desc('Четыре закрытые палаты вертушкой вокруг смещённой центральной передней; у каждой палаты два своих прохода наружу, деревянная дверь в переднюю и дверь к соседке, так что по палатам можно ходить и кольцом, и напрямую через центр. Северо-восток трапезная с очагом, юго-восток кладовая с рядами полок, юго-запад молельня с колоннами и шипами, северо-запад склеп с запертой на дверь каморкой в углу. В каморке лифт на 6 м вниз: под склепом секретная сокровищница с колоннами, боковой нишей и стражем.');
  const g = r.level(0), vault = r.level(-6);
  g.carve(-16.8, -16.8, 16.8, 16.8);

  // Вертушка: каждая перегородка идёт от угла передней к стене клетки, в ней дверь в переднюю и дверь к соседней палате.
  r.doorWall(-5.3, 4.5, 16.8, 4.5, [-1, 12]);
  r.doorWall(3, -16.8, 3, 4.2, [-10, 0.5]);
  r.doorWall(-16.8, -3, 2.7, -3, [-11, -1]);
  r.doorWall(-5, -2.7, -5, 16.8, [1, 11]);

  // Передняя.
  r.prop('Стол', 0.6, 0.6, 1, 2.2, 0.8);
  r.candle(0.6, 0.6, 0.8);
  r.monster('Sword', -2.6, -0.6, { ry: 45 });

  // Трапезная (северо-восток): длинный стол, каменный простенок режет угол между проходами.
  r.column(12.4, 12.2, { s: 2.6 });
  r.wall(4.6, 16.8, 4.6, 10.4, { th: 1 });
  for (const x of [-0.6, 2.2]) { r.prop('Стол', x, 12, 1, 4.4, 0.8); r.prop('Лавка', x - 0.8, 12, 0.4, 4, 0.45); r.prop('Лавка', x + 0.8, 12, 0.4, 4, 0.45); }
  r.prop('Очаг', -3.6, 16, 2, 1, 1.2);
  r.prop('Бочки', 15.4, 5.6, 1.6, 1.6, 1.3);
  r.torch(4, 14, 270); r.chest('Barrel', 15.6, 14, {}); r.monster('Warrior', 8, 8, { ry: 180 });

  // Кладовая (юго-восток): ряды полок дают коридоры, поперечный проход в середине.
  for (const [x, z, d] of [[6.8, -1.8, 7.6], [6.8, -11.2, 6], [10.4, -3.4, 6], [10.4, -12.2, 5], [14.2, -1.8, 6]]) r.prop('Полки с припасами', x, z, 0.9, d, 2.4);
  r.prop('Штабель ящиков', 13.2, -13.2, 2.4, 2.4, 2.4, { ry: 15 });
  r.chest('Crate', 12.4, -8.4); r.chest('LargeOakChest', 15.8, -15.6, { ry: 270 });
  r.torch(3.4, -6.6, 90);

  // Молельня (юго-запад): шахматные колонны, у западного прохода шипы, у восточной стены алтарь.
  for (const [x, z] of [[-13, -13], [-8.5, -6.6], [-3.5, -12.6], [-3, -7], [-12.4, -6.6]]) r.column(x, z, { s: 1.6, round: true });
  r.prop('Алтарь', 1.2, -14.6, 2, 1.4, 1.1);
  r.chest('SmallOakChest', 1.2, -12.8, { ry: 180 });
  for (const [x, z] of [[-14.2, -9.4], [-14.2, -7.4], [-8.4, -13.8]]) r.trap('Spike', x, z);
  r.brazier(-8, -11);
  r.monster('Archer', 0.4, -8, { ry: 270 });

  // Склеп (северо-запад): саркофаги поперёк и каморка лифта с дверью в углу.
  r.doorWall(-16.8, 11, -10.7, 11, [-14]);
  r.wall(-11, 11.3, -11, 16.8);
  for (const [x, z, ry] of [[-13.4, 0.6, 90], [-13.4, 4.4, 90], [-7.8, 5.6, 0]]) r.prop('Саркофаг', x, z, 1.1, 2.4, 1, { ry });
  r.chest('Coffin', -7.2, 0.2, { ry: 0 });
  r.torch(-5.4, 7.8, 270);
  r.monster('Sword', -10.4, 8.4, { ry: 90 });

  // Лифт в каморке, рычаги на обеих остановках.
  g.hole(-15.2, 13.6, -12.8, 16);
  r.lift(-14, 0, 14.8, 2.4, 2.4, -6);
  r.lever(-11.4, 0, 14.6, 270, { action: 'lift' });
  r.candle(-11.8, 12);

  // Сокровищница.
  vault.carve(-15.6, 3, -2, 16.2).carve(-2, 6, 6, 9.6).carve(6, 3.4, 12.6, 12.2);
  r.lever(-15.5, -6, 12.6, 90, { action: 'lift' });
  for (const [x, z] of [[-11, 11], [-6, 11], [-11, 6.8], [-6, 6.8]]) r.column(x, z, { y: -6, h: 5.4, s: 1.4, round: true });
  r.prop('Саркофаг', -8.6, 9, 1.4, 2.8, 1.1, { y: -6, ry: 90 });
  for (const [x, z] of [[-3.4, 15], [-5.6, 15], [-14.6, 4.2]]) r.chest('GoldPile', x, z, { y: -6 });
  // Боковая ниша за коротким ходом.
  r.prop('Алтарь', 11.4, 7.8, 1.2, 2.2, 1.1, { y: -6 });
  r.chest('GoldenChest', 9.8, 7.8, { y: -6, ry: 270 });
  r.monster('Warrior', 3, 7.8, { y: -6, ry: 270 }); r.monster('Mage', 8.6, 5.2, { y: -6, ry: 0 });
  r.brazier(-8.6, 13.6, -6); r.torch(12.2, 10.4, 270, -6);
  r.start(-8.4, 14.4, 180);
};
