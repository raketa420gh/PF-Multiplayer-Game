// Правка: сделай святилище более явным, модуль в целом более ступенчатым и с большим количеством комнат.
exports.options = { corner: true };
exports.build = r => {
  r.desc('Святилище занимает юго-западный угол на 6 м: двойные двери с севера и востока, ряды скамей и алтарь на помосте 7,25 м, за алтарём золотой сундук. К нему ведут две парадные лестницы уступами: северная 1,5–3–6 м и восточная 1,25–2,5–6 м. Посередине две комнаты на 1,5 и 2,5 м связывают лестницы между собой и с притвором, где подиум 1,5 м, а наверху между площадками ризница с двумя дверями. Боковые проходы вдоль стен уводят в склеп под святилищем с колоннами и гробами, оттуда чёрная лестница выходит к алтарю.');
  const g = r.level(0), up = r.level(6, 5);
  g.carve(-16.8, -16.8, 16.8, 16.8);
  const dirs = { N: [0, 1, 0], E: [1, 0, 90], S: [0, -1, 180], W: [-1, 0, 270] };
  const flight = (x, z, w, rise, dir, y0 = 0) => { const [dx, dz, ry] = dirs[dir], len = Math.ceil(rise * 13) / 10; r.stairs(x + dx * len / 2, z + dz * len / 2, w, len, rise, ry, y0); };
  const FULL = 5.4;

  // Верхний ярус: святилище, площадки лестниц, ризница, пустоты над парадными лестницами.
  up.carve(-16.8, -16.8, -3, -3);
  up.carve(-14, -3, -4, 13).hole(-14, -0.9, -4, 13);
  up.carve(-3, -14, 14, -4).hole(-0.6, -14, 14, -4);
  up.carve(-3, -4, -0.6, -3);
  up.carve(-4, -3, 3, 4);
  up.hole(-16.8, -9.5, -14.4, -5.2);

  // Северная парадная лестница: 0 → 1,5 → 3 → 6.
  flight(-9, 13, 4, 1.5, 'S');
  r.platform(-14, 5.5, -4, 11, 1.5);
  flight(-9, 7.5, 4, 1.5, 'S', 1.5);
  r.platform(-14, -0.9, -4, 5.5, 3);
  flight(-9, 3, 4, 3, 'S', 3);
  // Восточная парадная лестница: 0 → 1,25 → 2,5 → 6.
  flight(14, -9, 4, 1.25, 'W');
  r.platform(7.3, -14, 12.3, -4, 1.25);
  flight(9, -9, 4, 1.25, 'W', 1.25);
  r.platform(-0.6, -14, 7.3, -4, 2.5);
  flight(4, -9, 4, 3.5, 'W', 2.5);

  // Средние комнаты.
  r.platform(-4, -4, 2, 13, 1.5);    // галерея на 1,5
  r.platform(2, -4, 14, 4, 2.5);     // часовня на 2,5
  flight(0.7, 0, 2.4, 1, 'E', 1.5);
  r.platform(2, 4, 9, 11.5, 1.5);    // подиум притвора
  flight(5.5, 13.5, 3, 1.5, 'S');
  flight(11, 8, 2.4, 1.5, 'W');

  // Перегородки первого яруса.
  r.doorWall(-4, 5.5, -4, 13, [9], { y: 1.5, h: 3.9 });
  r.wall(-4, -4, -4, 5.5, { h: FULL });
  r.wall(-4, 13, 2, 13, { h: FULL });
  r.doorWall(2, 4, 2, 11.5, [8], { y: 1.5, h: 3.9 });
  r.doorWall(2, 11.5, 2, 16.8, [15], { h: FULL });
  r.doorWall(2, -4, 2, 4, [0], { y: 2.5, h: 2.9 });
  r.wall(2, 4, 14, 4, { h: FULL });
  r.doorWall(14, 4, 16.8, 4, [15.4], { h: FULL });
  r.wall(14, -4, 14, 4, { h: FULL });
  r.doorWall(3.5, -4, 7.3, -4, [5.4], { y: 2.5, h: 2.9 });
  r.wall(-4, -4, 3.5, -4, { h: FULL });
  r.wall(7.3, -4, 14, -4, { h: FULL });

  // Перегородки верхнего яруса.
  r.doorWall(-16.8, -3, -3, -3, [-9], { y: 6, h: 5, double: true });
  r.doorWall(-3, -16.8, -3, -3.3, [-9], { y: 6, h: 5, double: true });
  r.doorWall(-3, -3, -0.6, -3, [-1.8], { y: 6, h: 5 });
  r.doorWall(-4, -3.3, -4, 4, [-1.95], { y: 6, h: 5 });

  // Святилище: помост с алтарём, скамьи, колонны.
  r.platform(-16.8, -16.8, -10, -10, 7.25, 6);
  flight(-8.3, -13.5, 2.4, 1.25, 'W', 6);
  flight(-12.5, -8.3, 2.4, 1.25, 'S', 6);
  r.prop('Алтарь', -13.4, -13.4, 2.4, 1.2, 1.1, { y: 7.25, ry: 45 });
  r.chest('GoldenChest', -15.4, -15.4, { y: 7.25, ry: 45 });
  for (const z of [-15.6, -12.4, -6.8, -4.6]) r.prop('Скамья', -5.5, z, 0.7, 2.2, 0.5, { y: 6, ry: 0 });
  for (const x of [-11.6, -6.8]) r.prop('Скамья', x, -4.8, 2.2, 0.7, 0.5, { y: 6 });
  r.column(-10.2, -5.5, { y: 6, h: 5, round: true });
  r.column(-5.5, -10.2, { y: 6, h: 5, round: true });

  // Чёрная лестница из склепа на верхний ярус.
  flight(-15.6, -13, 2.2, 6, 'N');
  // Склеп.
  for (const [x, z] of [[-10, -9], [-10, -14], [-5, -9], [-5, -14]]) r.column(x, z, { h: FULL });
  r.prop('Саркофаг', -7.5, -11.5, 1.2, 2.4, 1);
  r.chest('Coffin', -12.4, -11.5);
  r.chest('Coffin', -2.2, -11.5);
  r.chest('Coffin', -7.5, -15.8, { ry: 90 });
  r.prop('Кости', -11, -3, 2, 1.2, 0.2);
  // Ризница, часовня, галерея, притвор.
  r.chest('LargeOakChest', 2.2, 3, { y: 6, ry: 270 });
  r.chest('Bookshelf', -3, 3.3, { y: 6 });
  r.prop('Стол', 0.5, 0.5, 1.8, 0.9, 0.8, { y: 6 });
  r.prop('Алтарь', 12.6, 0, 1.2, 2.4, 1.1, { y: 2.5 });
  r.chest('Urn', 12.6, 3, { y: 2.5 });
  for (const x of [5.5, 8.5]) r.prop('Скамья', x, 0, 0.7, 3, 0.5, { y: 2.5 });
  r.prop('Скамья', -2, 9, 0.7, 3, 0.5, { y: 1.5 });
  r.chest('Bookshelf', 1.4, -3, { y: 1.5 });
  r.chest('Urn', -3.2, 12.2, { y: 1.5 });
  r.column(12, 12, { h: FULL, round: true });

  r.monster('Mage', -8.5, -8.5, { y: 6, ry: 225 });
  r.monster('Warrior', -6.8, -11, { y: 6, ry: 180 });
  r.monster('Archer', -9, -2, { y: 6, ry: 0 });
  r.monster('Crossbow', -1.8, -9, { y: 6, ry: 90 });
  r.monster('Sword', -7.5, -6, { ry: 180 });
  r.monster('Skull', -2.5, -7);
  r.monster('Sword', 7, 0, { y: 2.5, ry: 90 });
  r.monster('Sword', -1, 8, { y: 1.5, ry: 180 });

  r.brazier(-11, -15.8, 7.25);
  r.brazier(-15.8, -11, 7.25);
  r.candle(-13.4, -11.9, 8.2);
  r.torch(-13.7, 4, 90, 3);
  r.torch(4, -13.7, 0, 2.5);
  r.candle(-5, -11.5);
  r.candle(12.6, -1, 3.6);
  r.torch(16.4, 11, 270);
  r.start(13, 14, 225);
};
