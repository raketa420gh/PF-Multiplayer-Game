// Правка: провал глубже, в два этажа, сложнее, со случайными препятствиями.
const MID = -5, BOT = -10;
// Устье провала и колодец к дну.
const MOUTH = [[-10.8, -9, 10.8, 9], [-6, 9, 7.2, 11.4], [-8, -12, 4, -9]], WELL = [-7, -6, 6.6, 5];

exports.options = {};
exports.build = r => {
  r.desc('Провал глубиной 10 м неправильной формы занимает почти всю клетку, по краю идёт кольцо с разбитыми колоннами и стенками. На −5 подковой лежит терраса: с кольца на неё ведут два марша, на северо-западе и юго-востоке, северный её конец под нависающим краем тупиковый, там сундук. С террасы ещё два марша спускаются к дну на −10: завалы, валуны и сломанные колонны стоят вразброс, а в низких гротах под террасой спрятаны сундуки и помост с золотым сундуком. Над провалом с севера на юг висит мост на одинокой опоре, самый быстрый и самый открытый путь.');
  const g = r.level(0), mid = r.level(MID), bot = r.level(BOT);
  g.carve(-16.8, -16.8, 16.8, 16.8);
  for (const m of MOUTH) { g.hole(...m); mid.carve(...m); }
  mid.hole(...WELL);
  bot.carve(...WELL);
  // Гроты на дне под террасой.
  bot.carve(6.6, -2, 10, 4);
  bot.carve(-4, 5, 2, 8.4);
  bot.carve(-1.6, -8.4, 2, -6);

  // Марши: кольцо → терраса (северо-запад, юго-восток), терраса → дно (запад, юг).
  r.stairs(-8.6, 5.8, 2.4, 6.4, 5, 0, MID);
  r.stairs(9.6, -5.8, 2.4, 6.4, 5, 180, MID);
  r.stairs(-3.8, -3, 2.4, 6.4, 5, 270, BOT);
  r.stairs(3.4, -2.8, 2.4, 6.4, 5, 180, BOT);

  // Мост на опоре.
  r.slab(-0.4, -12, 1.6, 11.4, 0);
  r.column(0.6, 1.5, { s: 3, y: BOT, h: 9.4 });
  for (const [x, z, d] of [[-0.35, -8, 3], [1.55, -4, 3], [-0.35, 6, 3.6], [1.55, 9, 3]]) r.prop('Парапет', x, z, 0.14, d, 1);

  // Рваный парапет устья.
  for (const [x, z, w, d] of [[-10.95, -4, 0.3, 5], [-10.95, 1, 0.3, 2.4], [10.95, 2, 0.3, 6], [5, -9.15, 4, 0.3], [-3.4, 11.55, 4, 0.3], [4.6, 11.55, 3, 0.3], [9, 9.15, 3.4, 0.3]]) r.prop('Парапет', x, z, w, d, 1);

  // Кольцо: стенки и разбитые колонны рвут простреливаемые стороны.
  r.wall(-0.6, 16.8, -0.6, 13.6, { th: 1.2, h: 3.2 });
  r.wall(13.4, 0.8, 16.8, 0.8, { th: 1.2, h: 3.2 });
  r.wall(3.6, -16.8, 3.6, -14, { th: 1.2, h: 3.2 });
  r.wall(-16.8, -1.2, -13.6, -1.2, { th: 1.2, h: 3.2 });
  for (const [x, z, s, h] of [[-12.4, 12.4, 1.2, 6], [12.4, 12.4, 1.2, 2.6], [12.4, -12.4, 1.2, 6], [-12.4, -12.4, 1.2, 3.4], [12.8, 5, 1, 1.8], [-12.8, 5.4, 1, 4]]) r.column(x, z, { s, h });
  r.prop('Обломки', 7.6, 14, 2.4, 1.4, 1.1, { ry: 15 });
  r.prop('Обломки', -5, -14, 2, 1.6, 1, { ry: 340 });
  r.prop('Обломки', 14.4, -4.4, 1.4, 2.2, 1.2, { ry: 10 });

  // Терраса: завалы, упавшая колонна, стенка-укрытие.
  r.prop('Обломки', -9.4, -5.8, 1.8, 1.4, 1, { y: MID, ry: 25 });
  r.block(-2.4, -7.6, 2.8, 0.7, { y: MID, h: 1.3, ry: 12 });
  r.prop('Обломки', 9.6, 0.8, 1.4, 2, 1.1, { y: MID, ry: 335 });
  r.column(7.6, 7, { s: 1, y: MID, h: 2.2, round: true });
  r.block(2, 7.8, 3.2, 0.8, { y: MID, h: 1.4, ry: 350 });
  r.chest('LargeOakChest', -4.8, 10.4, { y: MID, ry: 180 });
  r.chest('SmallOakChest', -10, -8.2, { y: MID, ry: 45 });

  // Дно: случайные валуны, завалы, сломанные колонны.
  for (const [x, z, w, d, h, ry] of [[-4.6, 2.4, 2.2, 1.6, 1.5, 20], [-1, 7.4, 1.2, 1.2, 2.6, 40], [-6, -0.6, 1, 1.4, 1.2, 15], [5.6, 3.4, 1.6, 1.2, 1.3, 335], [5.5, -4.8, 1.2, 1.2, 2.2, 30], [-5.6, -5.2, 1.4, 1, 1.1, 50], [1.2, 7.6, 1.4, 1, 1.6, 10]])
    r.block(x, z, w, d, { y: BOT, h, ry });
  r.prop('Обломки', -5.4, 4.2, 1.6, 1.2, 1, { y: BOT, ry: 70 });
  r.prop('Обломки', 2.4, 2.4, 1.4, 1.2, 0.9, { y: BOT, ry: 300 });
  r.prop('Кости', 0.4, -2.6, 1.6, 1.2, 0.2, { y: BOT });
  r.prop('Кости', -3, 6.6, 1.4, 1, 0.2, { y: BOT });
  r.trap('Spike', 5.4, 0.4, { y: BOT });
  r.chest('LargeOakChest', 0.2, -7.6, { y: BOT, ry: 0 });
  r.chest('Coffin', -3, 7.6, { y: BOT, ry: 180 });

  // Помост в восточном гроте.
  r.platform(7.6, -2, 10, 4, BOT + 1.2, BOT);
  r.stairs(6.6, 1, 2, 2, 1.2, 90, BOT);
  r.chest('GoldenChest', 9, 2.8, { y: BOT + 1.2, ry: 270 });

  // Свет: кольцо, терраса и дно.
  r.torch(-16.6, 12, 90);
  r.torch(16.6, -12, 270);
  r.brazier(-13, -6);
  r.brazier(8.8, 4.2, MID);
  r.torch(-10.6, -2, 90, MID);
  r.brazier(-3, -0.4, BOT);
  r.candle(8.2, 1, BOT + 1.2);
  r.candle(0.2, -6.8, BOT);

  r.monster('Sword', 12.6, 10.4, { ry: 225 });
  r.monster('Archer', 0.6, -6, { ry: 90 });
  r.monster('Sword', -9, -1.4, { y: MID, ry: 90 });
  r.monster('Archer', 8.6, -1.8, { y: MID, ry: 270 });
  r.monster('Warrior', 1, -4.2, { y: BOT, ry: 0 });
  r.monster('Skull', -3.4, 1, { y: BOT, ry: 90 });
  r.start(-8.4, 14.6, 180);
};
