// Правка: второй этаж, по центру дозорная башня с точкой интереса внутри; на втором этаже только верхушка башни;
// внизу пара комнат для смены караула.
exports.options = {};
exports.build = r => {
  r.desc('Два этажа. Внизу двор вокруг дозорной башни 10 × 10 м с сундуком внутри; вход в башню через дверь с юга. На западе и востоке две караульные смены с дверями, койками и столами. Лестница внутри башни выводит на открытую верхушку на 5 м: второй этаж пуст, с него виден весь двор.');
  const g = r.level(0), up = r.level(5, 5.4);
  // Двор и сплошной зал под верхним ярусом.
  g.carve(-16.8, -16.8, 16.8, 16.8);
  up.carve(-16.8, -16.8, 16.8, 16.8);
  // Пола второго этажа нет ничего, кроме верхушки башни: пролёт над всем двором, вокруг башни.
  up.hole(-16.8, -16.8, 16.8, -5.3); up.hole(-16.8, 5.3, 16.8, 16.8); up.hole(-16.8, -5.3, -5.3, 5.3); up.hole(5.3, -5.3, 16.8, 5.3);
  // Башня: стены до верхушки, дверь с юга.
  r.doorWall(-5, -5, 5, -5, [0], { h: 4.4 });
  r.wall(-5, 5, 5, 5, { h: 4.4 });
  r.wall(-5, -4.7, -5, 4.7, { h: 4.4 });
  r.wall(5, -4.7, 5, 4.7, { h: 4.4 });
  // Дыра в верхушке башни и марш вдоль северной стены.
  up.hole(0, -1.2, 2.4, 3.8);
  r.stairs(1.2, 0.6, 2.4, 6.4, 5, 0, 0);
  r.chest('GoldenChest', -3.2, 2.8, { ry: 90 });
  r.chest('LargeOakChest', -3.2, -2.8, { ry: 90 });
  r.candle(-3.8, 0);
  r.torch(4.6, -2, 270);
  // Парапет на верхушке.
  for (const [x, z, w, d] of [[-4.9, 0, 0.3, 10], [4.9, 0, 0.3, 10], [0, -4.9, 9.5, 0.3], [0, 4.9, 9.5, 0.3]]) r.prop('Парапет', x, z, w, d, 1, { y: 5 });
  r.torch(-4.7, -4.6, 0, 5);
  // Караульные смены вдоль западной и восточной стен.
  for (const s of [-1, 1]) {
    r.doorWall(s * 11, -12, s * 11, -4, [-8]);
    r.doorWall(s * 11, 4, s * 11, 12, [8]);
    r.wall(s * 11, -4, s * 11, 4);
    r.wall(s * 16.8, -4, s * 11.3, -4);
    r.wall(s * 16.8, 4, s * 11.3, 4);
    r.wall(s * 16.8, -12, s * 10.7, -12);
    r.wall(s * 16.8, 12, s * 10.7, 12);
    r.prop('Стол', s * 14, 0, 1.8, 0.9, 0.8);
    r.prop('Койка', s * 15.6, -2.4, 1, 2.1, 0.6);
    r.prop('Койка', s * 15.6, 2.4, 1, 2.1, 0.6);
  }
  r.torch(-11.4, 0, 270);
  r.torch(11.4, 0, 90);
  r.torch(0, 16.4, 180);
  r.torch(0, -16.4, 0);
  r.monster('Sword', 8, 0, { ry: 270 });
  r.monster('Archer', 0, 0, { y: 5, ry: 180 });
  r.start(-8, -14, 0);
};
