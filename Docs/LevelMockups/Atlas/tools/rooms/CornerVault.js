// Правка: сделай модуль более сложным и с ловушками, чем ближе к сокровищнице, тем больше.
exports.options = { corner: true };
exports.build = r => {
  r.desc('Сокровищница в юго-западном углу наглухо закрыта двумя плитами: они открываются двумя рычагами по порядку, первый в подвале, второй в тупике у её стены. Внешний зал и галереи почти чисты, две боковые галереи и две средние комнаты дают по паре ловушек, кольцевой коридор вокруг хранилища густо заставлен маятниками и шипами, а два участка пола в нём обваливаются в подвал, обходить их приходится по шипам. Внутри ловушек больше всего: северный вход обрушивается прямо за плитой, восточный идёт между маятниками, на двухступенчатом помосте шипы вокруг золотого сундука и груды золота. Подвал с лестницей в северную комнату возвращает упавших наверх.');
  const low = r.level(-5), g = r.level(0);
  const dirs = { N: [0, 1, 0], E: [1, 0, 90], S: [0, -1, 180], W: [-1, 0, 270] };
  const flight = (x, z, w, rise, dir, y0 = 0) => { const [dx, dz, ry] = dirs[dir], len = Math.ceil(rise * 13) / 10; r.stairs(x + dx * len / 2, z + dz * len / 2, w, len, rise, ry, y0); };

  // Внешний пояс.
  g.carve(3, 3, 16.8, 16.8);        // зал
  g.carve(-16.8, 10, 3, 16.8);      // северная галерея
  g.carve(10, -16.8, 16.8, 3);      // восточная галерея
  // Средний пояс.
  g.carve(-16.8, -5, -13, 10);      // западный проход
  g.carve(-5, -16.8, 10, -13);      // южный проход
  g.carve(-11, 1, 1, 8);            // северная комната
  g.carve(1, -11, 8, 1);            // восточная комната
  // Проёмы средних комнат.
  g.carve(-13, 2.8, -11, 5.2).carve(-6, 8, -3.6, 10).carve(1, 5.6, 3, 8);
  g.carve(4, 1, 6.4, 3).carve(8, -6.4, 10, -4).carve(3, -13, 5.4, -11);
  r.doorWall(-6, 9, -3.6, 9, [-4.8]);
  r.doorWall(9, -6.4, 9, -4, [-5.2]);
  // Кольцо вокруг хранилища и проёмы в него.
  g.carve(-16.8, -5, -1, -1);
  g.carve(-5, -16.8, -1, -1);
  g.carve(-7.2, -1, -4.8, 1).carve(-1, -7.2, 1, -4.8);
  // Хранилище и два входа за плитами.
  g.carve(-16.8, -16.8, -6, -6);
  g.carve(-12.2, -6, -9.8, -5).carve(-6, -12.2, -5, -9.8);
  r.secretDoor(-11, 0, -5.5, 2.4, 6, 1, [2.6, 0, 0]);
  r.secretDoor(-5.5, 0, -11, 1, 6, 2.4, [0, 0, 2.6]);

  // Подвал: под кольцом и под северным входом, лестница в северную комнату.
  low.carve(-13, -5, -1, -1).carve(-14, -9, -8, -5).carve(-3, -12, -1, -5).carve(-3.2, -1, -0.8, 5.5);
  g.hole(-3.2, 1, -0.8, 5.5);
  flight(-2, -1, 2.4, 5, 'N', -5);
  // Участки пола, которые обрушиваются: только там, где есть обход; северный вход хранилища — без обхода.
  g.hole(-11, -3, -7, -1).hole(-3, -12, -1, -8).hole(-13, -8, -9, -6);
  r.trap('Collapse', -9, -2);
  r.trap('Collapse', -2, -10, { ry: 90 });
  r.trap('Collapse', -11, -7);

  // Рычаги по порядку.
  r.lever(-12.9, -5, -3, 90, { order: 1 });
  r.lever(-4.9, 0, -15, 90, { order: 2 });

  // Ступени: помост внешнего зала, уступы средних комнат, двойной помост в хранилище.
  r.platform(11.5, 11.5, 16.8, 16.8, 1.25);
  flight(9.8, 13.5, 2.4, 1.25, 'E');
  r.platform(-11, 5.2, -6.8, 8, 1.5);
  flight(-8, 3.2, 2.4, 1.5, 'N');
  r.platform(1, -11, 8, -8.4, 1.25);
  flight(6, -6.7, 2.4, 1.25, 'S');
  r.platform(-16.8, -16.8, -10, -10, 1.25);
  flight(-8.3, -13, 2.4, 1.25, 'W');
  flight(-14, -8.3, 2.4, 1.25, 'S');
  r.platform(-16.8, -16.8, -13, -13, 2.5, 1.25);
  flight(-11.3, -15, 2, 1.25, 'W', 1.25);
  // Укрытия.
  r.column(6, 7, { s: 1.6 });
  r.block(0, 15, 2.4, 3.6);
  r.block(14.9, -3, 3.8, 2.4);
  r.prop('Парапет', 14.2, 11.65, 5.2, 0.3, 1, { y: 1.25 });
  r.column(13, -7, { s: 1.4 });
  r.prop('Штабель ящиков', -10, 13.5, 2, 1.6, 1.4);
  r.prop('Обломки', 6, -15, 1.8, 1.4, 0.8);
  r.prop('Парапет', -2, 0.85, 3, 0.3, 1);

  // Пояс 1 (внешний): две ловушки на весь зал и галереи.
  r.trap('Spike', 6, 12);
  r.trap('Spike', 13.5, -13);
  // Пояс 2 (проходы и комнаты): по одной–две на помещение.
  r.trap('Spike', -15, 6);
  r.trap('Blade', -15, 1, { ry: 90 });
  r.trap('Blade', 7, -15, { ry: 0 });
  r.trap('Spike', 1, -15);
  r.trap('Vent', -5, 4);
  r.trap('Vent', 3, -3);
  // Пояс 3 (кольцо): маятники поперёк, шипы на обходах обвалов, вентили.
  r.trap('Blade', -13, -3, { ry: 0 });
  r.trap('Blade', -6, -3, { ry: 0 });
  r.trap('Blade', -3, -6.5, { ry: 90 });
  r.trap('Blade', -3, -13, { ry: 90 });
  r.trap('Spike', -9, -4);
  r.trap('Spike', -4, -10);
  r.trap('Vent', -15, -3);
  r.trap('Vent', -3, -15);
  // Пояс 4 (хранилище): шипы, маятники у восточного входа, вентили, шипы на помосте.
  r.trap('Blade', -7.2, -13.5, { ry: 90 });
  r.trap('Blade', -7.2, -8.5, { ry: 90 });
  r.trap('Spike', -8.5, -11);
  r.trap('Spike', -7.5, -15.5);
  r.trap('Spike', -14, -7.5);
  r.trap('Spike', -11.5, -9);
  r.trap('Spike', -11.2, -11.2, { y: 1.25 });
  r.trap('Spike', -14.8, -11.4, { y: 1.25 });
  r.trap('Spike', -11.4, -13.4, { y: 1.25 });
  r.trap('Vent', -9, -15.8);
  r.trap('Vent', -15.8, -9);
  r.trap('Vent', -14.8, -14.8, { y: 2.5 });

  r.chest('GoldenChest', -15.8, -15.8, { y: 2.5, ry: 45 });
  r.chest('GoldPile', -14.2, -15.8, { y: 2.5 });
  r.chest('GoldPile', -15.8, -14.2, { y: 2.5 });
  r.chest('GoldPile', -12, -15.6, { y: 1.25 });
  r.chest('LargeOakChest', -15.6, -12, { y: 1.25, ry: 90 });
  r.chest('SmallOakChest', -12.2, -3, { y: -5, ry: 90 });
  r.chest('Urn', -13.4, -8.4, { y: -5 });
  r.chest('Urn', 15.8, 15.8, { y: 1.25 });
  r.chest('Crate', -15.8, 15.6);
  r.chest('Barrel', 2, -9.8, { y: 1.25 });
  r.chest('Urn', -10, 7, { y: 1.5 });

  r.monster('Warrior', -9, 5, { ry: 180 });
  r.monster('Crossbow', 13.5, 13.5, { y: 1.25, ry: 225 });
  r.monster('Sword', 5, -3, { ry: 0 });
  r.monster('Skull', -9, -3, { y: -5 });
  r.monster('Warrior', -10, -4, { ry: 90 });
  r.monster('Mage', -12, -12, { y: 1.25, ry: 45 });

  r.brazier(-13.5, -13.5, 2.5);
  r.brazier(-7, -7);
  r.torch(-1.4, -3, 270);
  r.candle(-12.2, -2, -5);
  r.torch(10, 16.4, 180);
  r.torch(16.4, 2, 270);
  r.torch(-16.4, 3, 90);
  r.start(11, 6, 225);
};
