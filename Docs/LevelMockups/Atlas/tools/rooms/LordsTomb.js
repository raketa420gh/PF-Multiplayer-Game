// Правка: величественная потайная гробница снизу; попасть, нажав плиты на полу по порядку; за ошибку из секретного отсека сверху падают монстры.
exports.options = {};
exports.build = r => {
  r.desc('Наверху обход вокруг закрытого двора с пятью нажимными плитами: две во дворе, три в нишах обхода, порядок показывают засечки. За каждую ошибку из потайного отсека над потолком в один из трёх люков падает монстр. Верная последовательность сдвигает каменную крышку у северной стены двора, под ней парадная лестница на 9 м вниз. Гробница высотой 8 м: колоннада вдоль марша, поперечный неф, помост с саркофагом лорда, сверху обходной балкон с двумя лестницами, под ним низкие склепы с гробами.');
  const hall = r.level(0), attic = r.level(7, 2.6), tomb = r.level(-9);

  // Верхний зал: крест, углы остаются скалой разного размера.
  hall.carve(-16.8, -10.4, 16.8, 10.4).carve(-10.4, -16.8, 10.4, 16.8);
  hall.carve(-12, 10, -10, 12).carve(10, -13, 13, -10);
  // Ниши обхода с плитами.
  hall.carve(-3, 13, 3, 16.8);

  // Двор: глухие стены с проходами в разных местах.
  r.wall(-6.4, 13, -4, 13); r.wall(-2, 13, 6.4, 13);
  r.wall(6.4, -5, 6.4, -1); r.wall(6.4, 2.4, 6.4, 13.3);
  r.wall(-6.4, -5, -6.4, 5.5); r.wall(-6.4, 8.6, -6.4, 13.3);
  r.wall(-6.7, -5, 0.8, -5); r.wall(4.4, -5, 6.7, -5);
  // Перегородки обхода режут прострелы вдоль стен.
  r.wall(0.6, 16.8, 0.6, 13.3, { th: 1 });
  r.wall(-16.8, -0.6, -10.6, -0.6, { th: 1.4 });
  r.wall(16.8, 1.4, 11.2, 1.4, { th: 1 });
  r.wall(-1.5, -16.8, -1.5, -11, { th: 1.2 });
  r.column(-8.6, 3, { s: 1.4, h: 6.4 }); r.column(9, -6.5, { s: 1.4, h: 6.4 }); r.column(-9, -8.8, { s: 1.4, h: 6.4 }); r.column(8.2, 10, { s: 1.4, h: 6.4 });
  r.prop('Обломки', 4, -10, 3, 2, 1.4, { ry: 20 });
  r.prop('Саркофаг', -13.5, 5, 1.1, 2.4, 1, { ry: 90 });
  r.prop('Саркофаг', 13, -6, 1.1, 2.4, 1);

  // Колодец лестницы под крышкой; парапет оставляет вход только с севера.
  hall.hole(-1.6, 6.7, 1.6, 11);
  r.prop('Парапет', -1.75, 8.85, 0.3, 4.6, 1); r.prop('Парапет', 1.75, 8.85, 0.3, 4.6, 1); r.prop('Парапет', 0, 6.55, 3.8, 0.3, 1);
  // Крышка уходит в толщу пола на восток.
  r.secretDoor(0, -0.55, 8.85, 3.2, 0.5, 4.3, [3.4, 0, 0]);

  // Плиты: порядок разводит игрока по всему залу.
  r.plate(-3, 0, 1); r.plate(13.5, 4.4, 2); r.plate(-1, 15, 3); r.plate(-13.5, -4.4, 4); r.plate(3.4, 3, 5);
  // Секретный отсек над потолком: три камеры, из каждой люк.
  for (const [x, z] of [[0, -9], [-10, 6], [11, 5]]) {
    attic.carve(x - 2, z - 2, x + 2, z + 2).hole(x - 0.7, z - 0.7, x + 0.7, z + 0.7);
    r.drop(x, 6.4, z);
  }

  r.torch(-6, 2, 90); r.torch(6, 9, 270); r.brazier(0, 4.6);
  r.monster('Sword', -6, -13, { ry: 45 });
  r.monster('Skull', 12, 8.4, { ry: 270 });
  r.chest('SmallOakChest', -13.5, 7);
  r.start(8.4, -14.5, 0);

  // Гробница: марш в нефе с колоннадой, поперечный неф, помост на юге.
  tomb.carve(-6.5, -2, 6.5, 12).carve(-16, -16, 16, -1.5);
  r.stairs(0, 5.5, 3.2, 11, 9, 0, -9);
  for (const z of [10, 5.5, 1]) for (const s of [-1, 1]) r.column(s * 4, z, { y: -9, h: 8.4, round: true });
  // Торцевые ниши нефа с гробами.
  r.chest('Coffin', -5.6, 7.8, { y: -9, ry: 90 }); r.chest('Coffin', 5.6, 3.2, { y: -9, ry: 270 });
  // Помост.
  r.platform(-5, -11.2, 5, -5, -7.8, -9);
  r.stairs(0, -4, 3.2, 2, 1.2, 180, -9);
  r.prop('Саркофаг', 0, -8, 2, 3.2, 1.2, { y: -7.8 });
  r.chest('GoldenChest', 0, -10.4, { y: -7.8 });
  r.monster('Warrior', 0, -5.6, { y: -7.8 }); r.brazier(-3.6, -7, -7.8); r.brazier(3.6, -7, -7.8);
  // Балкон над склепами, две лестницы по краям: петля вокруг помоста.
  r.slab(-15.8, -15.8, 15.8, -12.4, -5);
  r.stairs(-14.2, -9.4, 2.6, 6, 4, 180, -9);
  r.stairs(14.2, -9.4, 2.6, 6, 4, 180, -9);
  r.prop('Парапет', 0, -12.55, 22.6, 0.3, 1, { y: -5 });
  r.monster('Mage', 0, -14, { y: -5 }); r.chest('LargeOakChest', 12.4, -14.8, { y: -5, ry: 180 });
  // Склепы под балконом: глухие перегородки делят полосу на ячейки с разными входами.
  for (const x of [-11, -3.6, 3.6, 11]) r.wall(x, -15.9, x, -13.2, { y: -9, h: 3.4 });
  for (const [x, ry] of [[-13.4, 0], [-7.4, 0], [0, 0], [7.4, 180], [13.4, 180]]) r.chest('Coffin', x, -14.8, { y: -9, ry });
  r.monster('Sword', 9, -7, { y: -9, ry: 270 }); r.monster('Archer', -9, -3, { y: -9, ry: 180 });
  r.torch(-15.6, -6, 90, -9); r.torch(15.6, -6, 270, -9);
};
