// Правка: сделай казарму многоуровневой с большим количеством комнат и комнатой оружейной, можешь сделать 2 этажа.
exports.options = { corner: true };
exports.build = r => {
  r.desc('Два этажа и полуэтажи, всего тринадцать комнат. Внизу караулка, лестничный зал, плац с трибуной, две спальни (одна поднята на 1,25 м), столовая с помостом, склад и восточные сени; в центре учебный зал высотой в оба этажа. Наверху галерея вокруг него: оружейная со стойками на западе с двустворчатой дверью, комната офицера с помостом 6,25 м, третья спальня и каморка сержанта. Этажи связаны двумя лестницами на севере и юге, а чёрный марш из спальни выводит прямо в оружейную.');
  const g = r.level(0), up = r.level(5, 5);
  g.carve(-16.8, -16.8, 16.8, 16.8);
  const dirs = { N: [0, 1, 0], E: [1, 0, 90], S: [0, -1, 180], W: [-1, 0, 270] };
  const flight = (x, z, w, rise, dir, y0 = 0) => { const [dx, dz, ry] = dirs[dir], len = Math.ceil(rise * 13) / 10; r.stairs(x + dx * len / 2, z + dz * len / 2, w, len, rise, ry, y0); };
  const H = 4.4, HALF = { y: 1.25, h: H - 1.25 }, UP = { y: 5, h: 5 };
  const cot = (x, z, y = 0, along = 'z') => along === 'z' ? r.prop('Койка', x, z, 1, 2.1, 0.6, { y }) : r.prop('Койка', x, z, 2.1, 1, 0.6, { y });

  // Верхний ярус: комнаты и галерея, вырезаны одним куском, разделены стенами.
  up.carve(-16.8, -6, 16.8, 16.8);
  up.carve(-9, -16.8, 2, -6);
  up.hole(-5.4, -3.4, 2.4, 2.4);              // пустота учебного зала
  up.hole(-2.7, 9, -0.3, 13.5);             // северная лестница
  up.hole(-4.7, -14.5, -2.3, -10);          // южная лестница
  up.hole(-16.8, -3.5, -14.2, 0.9);           // чёрный марш

  // Лестницы между этажами.
  flight(-1.5, 7, 2.4, 5, 'N');
  flight(-3.5, -8, 2.4, 5, 'S');
  flight(-15.5, -4, 2.4, 3.75, 'N', 1.25);

  // Первый этаж, стены z = 5 и z = -6.
  r.platform(-16.8, -6, -8, 5, 1.25);         // спальня на полуэтаже
  flight(-12, 6.7, 2.4, 1.25, 'S');
  r.doorWall(-16.8, 5, -8, 5, [-12], HALF);
  r.doorWall(-8, 5, 5, 5, [-1.5], { h: H });
  r.doorWall(5, 5, 16.8, 5, [10], { h: H });
  flight(-13, -7.7, 2.4, 1.25, 'N');
  r.doorWall(-16.8, -6, -8, -6, [-13], HALF);
  r.doorWall(-8, -6, 2, -6, [-3.5], { h: H });
  r.doorWall(2, -6, 16.8, -6, [8], { h: H });
  // Поперечные стены.
  r.doorWall(-6, 5, -6, 16.8, [12], { h: H });
  r.doorWall(3, 5, 3, 16.8, [13], { h: H });
  flight(-6.3, -1, 2.4, 1.25, 'W');
  r.doorWall(-8, -6, -8, 5, [-1], HALF);
  r.doorWall(5, -6, 5, 5, [1], { h: H });
  r.doorWall(-9, -16.8, -9, -6, [-12], { h: H });
  r.doorWall(2, -16.8, 2, -6, [-11], { h: H });

  // Верхний этаж.
  r.wall(-16.8, 5, -8, 5, UP);
  r.wall(-8, 5, -6, 5, UP);
  r.wall(3, 5, 5, 5, UP);
  r.wall(5, 5, 16.8, 5, UP);
  r.doorWall(-6, 5, -6, 16.8, [12], UP);
  r.doorWall(3, 5, 3, 16.8, [9], UP);
  r.doorWall(-8, -6, -8, 5, [0], { ...UP, double: true });
  r.doorWall(5, -6, 5, 5, [-2], UP);
  r.wall(-9, -6, -8, -6, UP);
  // Парапет галереи над учебным залом.
  r.prop('Парапет', -5.55, -2.5, 0.3, 1.8, 1, { y: 5 });
  r.prop('Парапет', 2.55, 1.2, 0.3, 2.4, 1, { y: 5 });
  r.prop('Парапет', -1, 2.55, 5, 0.3, 1, { y: 5 });

  // Полуэтажи и помосты.
  r.platform(12, 12, 16.8, 16.8, 1.25);       // трибуна плаца
  flight(10.3, 14.2, 2.4, 1.25, 'E');
  r.platform(11, -6, 16.8, 5, 1.25);          // помост столовой
  flight(9.3, -2, 2.4, 1.25, 'E');
  r.platform(-16.8, 11, -11, 16.8, 6.25, 5);  // помост офицера
  flight(-13, 9.3, 2.4, 1.25, 'N', 5);

  // Караулка.
  r.prop('Стол', -13, 11, 1.8, 0.9, 0.8);
  r.prop('Лавка', -13, 12.1, 1.8, 0.4, 0.45);
  r.prop('Лавка', -13, 9.9, 1.8, 0.4, 0.45);
  r.chest('Crate', -16, 15.8);
  // Лестничный зал.
  r.prop('Штабель ящиков', 2, 15.6, 1.4, 1.6, 1.4);
  // Плац.
  r.column(6.5, 11, { h: H, round: true });
  r.column(11, 7.5, { h: H, round: true });
  r.chest('Barrel', 15.8, 15.8, { y: 1.25 });
  // Спальня на полуэтаже.
  for (const z of [1.4, 3.7, -3.4]) cot(-9, z, 1.25);
  for (const z of [-1, -3.5]) cot(-12, z, 1.25);
  // Южная спальня.
  for (const z of [-15.5, -13.2, -10.9, -8.6]) cot(-16, z);
  for (const x of [-13, -10.7]) cot(x, -16.1, 0, 'x');
  r.chest('SmallOakChest', -10, -7.6, { ry: 180 });
  // Учебный зал.
  r.prop('Штабель ящиков', 3.6, -4.4, 1.6, 1.6, 1.2);
  r.prop('Обломки', -5.8, 3.4, 1.6, 1.2, 0.8);
  // Столовая.
  for (const x of [7.5]) { r.prop('Стол', x, 2, 0.9, 3, 0.8); r.prop('Лавка', x - 0.8, 2, 0.4, 3, 0.45); r.prop('Лавка', x + 0.8, 2, 0.4, 3, 0.45); }
  r.prop('Стол', 13.5, 2.5, 3, 0.9, 0.8, { y: 1.25 });
  r.prop('Лавка', 13.5, 3.4, 3, 0.4, 0.45, { y: 1.25 });
  r.prop('Очаг', 15.6, -2, 1.6, 2.4, 1, { y: 1.25 });
  r.prop('Котёл', 14, -4.6, 1, 1, 0.9, { y: 1.25 });
  // Склад.
  r.chest('Crate', 0.8, -15.8);
  r.chest('Crate', 0.8, -8);
  r.prop('Штабель ящиков', -7.8, -15.4, 1.8, 2, 1.6);
  r.prop('Мешки', -7.8, -8.4, 1.6, 1.6, 0.8);
  r.prop('Полки с припасами', 1.2, -13, 0.6, 3, 2);
  // Сени.
  r.prop('Бочки', 6, -15.4, 2, 1.6, 1.2);
  r.prop('Штабель ящиков', 11, -12, 2, 2, 1.4);
  r.chest('Barrel', 16, -15.8);

  // Оружейная.
  for (const x of [-15.5, -12.5, -10]) r.prop('Стойка с оружием', x, 4.3, 2.2, 0.5, 1.8, { y: 5 });
  for (const x of [-13, -10.5]) r.prop('Стойка с оружием', x, -5.4, 2.2, 0.5, 1.8, { y: 5 });
  r.prop('Стойка с оружием', -12, -0.5, 0.6, 3.6, 1.8, { y: 5 });
  r.chest('LargeOakChest', -15.8, -5, { y: 5, ry: 45 });
  // Офицер.
  r.prop('Стол', -9, 8, 1.8, 0.9, 0.8, { y: 5 });
  cot(-7.3, 15, 5);
  cot(-15.6, 12.4, 6.25);
  r.chest('LargeOakChest', -15.6, 15.6, { y: 6.25, ry: 135 });
  // Спальня наверху.
  for (const z of [15.4, 13.1, 10.8, 8.4]) cot(16, z, 5);
  for (const x of [7, 9.3, 11.6]) cot(x, 16, 5, 'x');
  r.chest('Crate', 9, 6, { y: 5 });
  // Сержант.
  r.prop('Стол', 13, -2, 0.9, 1.8, 0.8, { y: 5 });
  cot(16, 3, 5);
  r.chest('SmallOakChest', 16, -5.2, { y: 5, ry: 270 });
  // Верхний склад над лестницей.
  r.prop('Полки с припасами', 1.2, -15, 0.6, 3, 2, { y: 5 });

  r.monster('Sword', -13, 8, { ry: 0 });
  r.monster('Sword', -11, 3, { y: 1.25, ry: 90 });
  r.monster('Warrior', -1, 0, { ry: 180 });
  r.monster('Sword', 8, -3, { ry: 90 });
  r.monster('Archer', 14, 14, { y: 1.25, ry: 225 });
  r.monster('Crossbow', -9.5, 0, { y: 5, ry: 90 });
  r.monster('Archer', 4, 0, { y: 5, ry: 270 });
  r.monster('Warrior', -9, 13, { y: 5, ry: 90 });
  r.monster('Sword', 10, 11, { y: 5, ry: 270 });

  r.brazier(1.5, 1.5);
  r.torch(16.4, 11, 270);
  r.torch(-16.4, 8, 90);
  r.candle(7.5, 2, 0.8);
  r.candle(-13, -1, 5);
  r.torch(-14, 16.4, 180, 5);
  r.torch(4, -0.5, 270, 5);
  r.torch(8, 16.4, 180, 5);
  r.start(13, 8, 225);
};
