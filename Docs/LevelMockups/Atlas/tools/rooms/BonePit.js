// Правка: сделай яму более глубокой и модуль в целом более ступенчатым.
exports.options = { corner: true };
exports.build = r => {
  r.desc('Яма 23 × 23 м уходит на 10 м вниз четырьмя полками, которые спиралью обходят её по часовой: −2,5, −4, −5,25 и −6,75 м; затем ступень −8,5 и дно с роем черепов, большим сундуком и гробами. Кроме спирали на западную полку ведёт длинный марш с южного края, а на восточную — потайной спуск из туннеля у восточной стены. По краю ямы идёт кольцо обхода на нуле. Вокруг него в углах и между проёмами приступки 1,25–3,25 м с лестницами, со стрелками и сундуками.');
  const pit = r.level(-10), g = r.level(0);
  g.carve(-16.8, -16.8, 16.8, 16.8).hole(-15, -15, 8, 8);
  pit.carve(-15, -15, 8, 8);
  const dirs = { N: [0, 1, 0], E: [1, 0, 90], S: [0, -1, 180], W: [-1, 0, 270] };
  const flight = (x, z, w, rise, dir, y0 = 0) => { const [dx, dz, ry] = dirs[dir], len = Math.ceil(rise * 13) / 10; r.stairs(x + dx * len / 2, z + dz * len / 2, w, len, rise, ry, y0); };

  // Полки спирали, от края к дну.
  r.platform(-15, 3.5, 8, 8, -2.5, -10);        // северная
  r.platform(-15, -15, -10.5, 3.5, -4, -10);    // западная
  r.platform(-10.5, -15, 8, -10.5, -5.25, -10); // южная
  r.platform(3.5, -10.5, 8, 3.5, -6.75, -10);   // восточная
  r.platform(-1, -10.5, 3.5, 3.5, -8.5, -10);   // ступень над дном
  // Марши спирали.
  flight(4, 4.7, 2.4, 2.5, 'N', -2.5);
  flight(-12.75, 1.5, 2.4, 1.5, 'N', -4);
  flight(-8.8, -12.75, 2.4, 1.25, 'W', -5.25);
  flight(5.75, -8.5, 2.4, 1.5, 'S', -6.75);
  flight(1.2, -3, 2.4, 1.75, 'E', -8.5);
  flight(-3, 1, 2.4, 1.5, 'E', -10);
  // Прямой марш с южного края на западную полку.
  flight(-13.8, -9.8, 2.4, 4, 'S', -4);
  // Туннель: с востока на восточную полку, под полом верхнего яруса.
  pit.carve(8, -4.2, 14.8, -1.8);
  g.hole(10, -4.2, 14.8, -1.8);
  flight(6, -3, 2.4, 6.75, 'E', -6.75);
  r.prop('Парапет', 12.4, -4.35, 4.8, 0.3, 1);
  r.prop('Парапет', 12.4, -1.65, 4.8, 0.3, 1);

  // Приступки вокруг ямы.
  r.platform(-16.8, 10.5, -11, 16.8, 1.5);
  flight(-9, 12.6, 2.4, 1.5, 'W');
  r.platform(-16.8, 13, -13.5, 16.8, 3.25, 1.5);
  flight(-15, 10.7, 2.2, 1.75, 'N', 1.5);
  r.platform(-4, 11.5, 4.5, 16.8, 1.25);
  flight(0, 9.8, 2.4, 1.25, 'N');
  r.platform(-1, 14, 2.5, 16.8, 2.75, 1.25);
  flight(-3, 15.4, 2, 1.5, 'E', 1.25);
  r.platform(11.5, 11.5, 16.8, 16.8, 2);
  flight(8.9, 13, 2.4, 2, 'E');
  r.platform(10, -16.8, 16.8, -11.5, 1.25);
  flight(12, -9.8, 2.4, 1.25, 'S');
  r.platform(13.5, -16.8, 16.8, -14, 2.75, 1.25);
  flight(11.5, -15.4, 2, 1.5, 'E', 1.25);

  // Парапет на кромке там, где нет маршей.
  r.prop('Парапет', -7, 8.15, 9, 0.3, 1);
  r.prop('Парапет', 8.15, 3.5, 0.3, 7, 1);
  r.prop('Парапет', 8.15, -11, 0.3, 6, 1);
  r.prop('Парапет', -4, -15.15, 12, 0.3, 1);
  // Колонны из ямы: укрытие на полках и перекрытие линии через яму.
  r.column(-5, -3, { y: -10, h: 16, s: 1.8, round: true });
  r.column(6, 6, { y: -2.5, h: 8.5, s: 1.4, round: true });

  // Дно.
  r.chest('LargeOakChest', -8.6, -8.6, { y: -10, ry: 45 });
  r.chest('Coffin', -9.4, 1.8, { y: -10 });
  r.chest('Coffin', -6.5, 2.6, { y: -10, ry: 90 });
  for (const [x, z, w] of [[-4, -8, 2.4], [-8, -3, 1.8], [-2.4, -5.5, 1.6]]) r.prop('Кости', x, z, w, 1.6, 0.2, { y: -10 });
  r.prop('Черепа', -6, 0, 1.4, 1.4, 0.25, { y: -10 });
  r.prop('Обломки', -6.8, -5.8, 1.6, 1.4, 0.8, { y: -10 });
  for (const [x, z] of [[-7, -7], [-3, -7.5], [-8, 0], [-3, 2], [-6, -2], [-2.5, -2]]) r.monster('Skull', x, z, { y: -10 });
  // Полки.
  r.chest('Urn', 1, -9.8, { y: -8.5 });
  r.chest('Urn', -13.6, 7, { y: -2.5 });
  r.chest('Coffin', 7, -9.5, { y: -6.75 });
  r.prop('Кости', 0, 6, 3, 1.6, 0.2, { y: -2.5 });
  r.monster('Sword', -12, -2, { y: -4, ry: 90 });
  r.monster('Warrior', 4.8, -13, { y: -5.25, ry: 270 });
  r.monster('Sword', 5, -1, { y: -6.75, ry: 270 });
  // Приступки.
  r.chest('SmallOakChest', -15.6, 15.6, { y: 3.25, ry: 135 });
  r.chest('Crate', 15.6, -15.8, { y: 2.75 });
  r.chest('Barrel', 15.8, 15.8, { y: 2 });
  r.monster('Archer', 0.8, 15.4, { y: 2.75, ry: 180 });
  r.monster('Archer', 15, -15, { y: 2.75, ry: 315 });
  r.monster('Crossbow', -15, 15, { y: 3.25, ry: 135 });
  r.monster('Sword', 12, 3, { ry: 270 });

  r.brazier(-11, 13, 1.5);
  r.brazier(14, 14, 2);
  r.torch(16.4, 2, 270);
  r.torch(13, -16.4, 0, 1.25);
  r.candle(-8.6, -7.4, -10);
  r.candle(-8, 2.4, -10);
  r.brazier(1, 1.8, -8.5);
  r.start(13, 6, 225);
};
