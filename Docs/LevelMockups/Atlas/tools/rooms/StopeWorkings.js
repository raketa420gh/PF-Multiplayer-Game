  const low = r.level(LOW), g = r.level(0, H);
  g.carve(-16.8, -16.8, 16.8, 16.8);
  const rock = (x, z, w, d, ry = 0) => r.block(x, z, w, d, { h: H, ry });
  const prop = (n, x, z, w, d, h, y = 0, ry = 0) => r.prop(n, x, z, w, d, h, { y, ry });
