  // Карманы под просевшей кровлей: примыкают к жиле.
  const POCKET = [[-14, 6.4, -10.2, 8.4], [0.2, -9, 2.2, -5], [6.6, -12.4, 10.6, -10.4]];
  for (const v of [...VEIN, ...POCKET]) { low.carve(...v); g.hole(...v); }
  r.trap('Collapse', -12.1, 7.4); r.trap('Collapse', 1.2, -7, { ry: 90 }); r.trap('Collapse', 8.6, -11.4);
  r.stairs(-13, 11.6, 2.4, 2, 1.25, 270, LOW); r.stairs(-4.8, 7.6, 2.4, 2, 1.25, 90, LOW);
  r.stairs(-3.2, 3.2, 2.4, 2, 1.25, 0, LOW); r.stairs(5.8, -4, 2.8, 2, 1.25, 90, LOW);
  r.stairs(9.8, -7.2, 2.4, 2, 1.25, 270, LOW); r.stairs(11.8, -12, 2.4, 2, 1.25, 180, LOW);

  // Уступы +1,25: марш до +1 и порог 0,25, иначе голова упирается в кровлю.
  for (const a of [[2, 4, 8, 11.4], [4, 1.4, 11.4, 7], [9, 6, 13, 9]]) r.platform(...a, HIGH);
  for (const a of [[-13.4, -11.6, -6, -6.4], [-10.4, -7, -3, -3.4], [-15, -6.8, -10, -4.4]]) r.platform(...a, HIGH);
  r.stairs(1, 7, 2.4, 2, 1, 90); r.stairs(7, 0.4, 2.4, 2, 1, 0); r.stairs(-6, -2.4, 2.4, 2, 1, 180); r.stairs(-5, -9.4, 2.4, 2, 1, 270);

  // Целики у стен: перемычки рвут периметр; углы завалены.
  rock(0.6, 15.1, 5.2, 3.4, 0); rock(15.4, -0.8, 2.8, 6, 0); rock(-1, -15.1, 6, 3.4, 0); rock(-15.1, 1.2, 3.4, 5.6, 0);
  rock(15, 15, 3.6, 3.6, 0); rock(-15.5, -15.5, 2.6, 2.6, 0); rock(15, -15, 3.6, 3.6, 0); rock(-15.2, 15.2, 3.2, 3.2, 0);
  // Целики в глубине: разный размер, сбитый шаг, поворот.
  for (const a of [
    [0.4, 10.4, 2.4, 2.2, 12], [5.4, 14.6, 1.8, 1.8, 20], [4, 9.4, 1.8, 1.8, 20], [7, 9, 2.6, 1.6, 340], [12.6, 11.4, 2.2, 3, 15], [4.6, 4.6, 1.6, 1.8, 40], [10.6, 4.2, 2.4, 1.8, 10], [15.8, 3.4, 2, 1.8, 0],
    [9.2, -2.2, 2.4, 2.4, 25], [-12.6, 2.8, 3, 2, 15], [-7.6, 2.8, 2.2, 2.4, 30], [-12.8, -1.8, 2, 3, 350], [-8, -5.2, 2.6, 1.8, 10], [-12.4, -9.4, 1.6, 1.8, 0],
    [-8.6, -9.4, 1.8, 2.2, 40], [-3.8, -6.8, 2.4, 1.8, 15], [-5.2, -15.2, 2, 2.2, 0], [4.8, -8, 2, 2.4, 345], [3.6, -12.8, 2.4, 2, 10], [-6, 12.6, 1.8, 1.8, 25], [-9.4, -1, 1.8, 1.6, 15], [15.6, -11.4, 2.2, 2, 20], [-11, 14, 1.8, 1.8, 15], [-11.6, -13.4, 1.4, 1.4, 0]]) rock(...a);

  // Крепь, обломки, вагонетка на рельсах жилы.
  for (const [x, z] of [[-1, 6.4], [9, 13.4], [-11, 0.6], [-1.6, -3.4], [6.6, -5.6], [-3.2, -11.6], [11.2, 0.4], [-8.8, 4.6]]) timber(x, z);
  prop('Рудная вагонетка', 8.4, 4.6, 2, 1.1, 1.2, HIGH); prop('Рудная вагонетка', 4.6, -3.1, 2, 1.1, 1.2, LOW);
  prop('Обломки', 11, 7.8, 1.8, 1.2, 0.9, HIGH); prop('Обломки', -8.6, -11, 1.6, 1.4, 0.9, HIGH, 20);
  prop('Обломки', 0.4, -12.6, 1.6, 1, 1); prop('Обломки', -5.4, 9.8, 1.8, 1, 1, 0, 340); prop('Обломки', 9.4, 13.8, 1.6, 1.2, 1); prop('Обломки', 14.4, -10.4, 1.6, 1.2, 1); prop('Кости', -1.2, 2.2, 1.4, 1, 0.2, LOW);
  prop('Обломки', -2.8, 0.8, 1.6, 1, 1, LOW, 0);

  // Ловушки и добыча сгущаются к юго-восточному концу жилы.
  r.trap('Spike', 2, -3.8, { y: LOW }); r.trap('Spike', 1.4, -7.8, { y: LOW }); r.trap('Spike', 11.8, -9.4, { y: LOW }); r.trap('Spike', 10.6, -7.2, { y: LOW }); r.trap('Blade', 10, -11.4, { y: LOW, ry: 90 }); r.trap('Spike', 8.4, -11.4, { y: LOW });
