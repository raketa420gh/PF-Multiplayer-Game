// Правка: тюрьма двухэтажная, этаж выше. Сигнатура — тюремный блок: улицы решёткой «#», камеры за bars на обоих этажах.
exports.options = {};
exports.build = r => {
  r.desc('Два этажа тюремного блока. Внизу улицы решёткой «#» от всех проёмов с четырьмя калитками, за решётками камеры с открытыми дверцами; центр занимает пост тюремщиков, двухсветный атриум с маршем на галерею. В северо-восточном и юго-западном углах ещё по маршу: они выводят на концы верхних улиц, так что между этажами есть петли. Наверху кольцо улиц вокруг галереи, те же ряды камер за решётками и две караулки в углах.');
  const Y = 5, H = 4.4, g = r.level(0), up = r.level(Y, H);
  g.carve(-16.8, -16.8, 16.8, 16.8); up.carve(-16.8, -16.8, 16.8, 16.8);
  up.hole(-4.2, -4.2, 4.2, 4.2); up.hole(14.4, 9.8, 16.8, 16.8); up.hole(-16.8, -16.8, -14.4, -9.8);
  r.stairs(3, 1, 2.4, 6.4, Y, 0);
  r.stairs(15.6, 12.775, 2.4, 5.95, Y, 180); r.stairs(-15.6, -12.775, 2.4, 5.95, Y, 0);

  // Сторона блока в локальных координатах: u вдоль улицы, v от центра наружу.
  const sides = { N: (u, v) => [u, v], E: (u, v) => [v, -u], S: (u, v) => [-u, -v], W: (u, v) => [-v, u] };
  const cells = (side, y, list) => {
    const P = sides[side], line = (u1, v1, u2, v2, fn) => { const [a, b] = P(u1, v1), [c, d] = P(u2, v2); fn(a, b, c, d); };
    // Перегородки улицы и камеры; дверца — разрыв решётки 1,8 м со смещением, у каждой камеры свой.
    line(-6.7, 10.4, -6.7, 16.8, (a, b, c, d) => r.wall(a, b, c, d, { y, h: H })); line(6.7, 10.4, 6.7, 16.8, (a, b, c, d) => r.wall(a, b, c, d, { y, h: H }));
    line(-6.7, 10.1, 6.7, 10.1, (a, b, c, d) => r.wall(a, b, c, d, { th: 0.3, y: y + 3, h: H - 3 }));
    list.forEach(([a, b, off], i) => {
      const g0 = (a + b) / 2 + off;
      line(a, 10.1, g0 - 0.9, 10.1, (x1, z1, x2, z2) => r.bars(x1, z1, x2, z2, y));
      line(g0 + 0.9, 10.1, b, 10.1, (x1, z1, x2, z2) => r.bars(x1, z1, x2, z2, y));
      if (i) line(a - 0.2, 10.25, a - 0.2, 16.8, (x1, z1, x2, z2) => r.wall(x1, z1, x2, z2, { th: 0.4, y, h: H }));
    });
  };
  const three = [[-6.4, -2.4, -0.6], [-2, 2, 0.6], [2.4, 6.4, 0]], threeB = [[-6.4, -2.4, 0.6], [-2, 2, 0], [2.4, 6.4, -0.6]], two = [[-6.4, -0.2, 1.4], [0.2, 6.4, -1.4]];
  cells('N', 0, three); cells('E', 0, threeB); cells('S', 0, two); cells('W', 0, three);
  cells('N', Y, two); cells('E', Y, three); cells('S', Y, threeB); cells('W', Y, two);

  // Атриум: двери внизу, арки на галерее, вертушкой.
  const atrium = (y, door, n, e, s, w) => {
    r.doorWall(-7, 6.7, 7, 6.7, [n], { y, h: H, door }); r.doorWall(-7, -6.7, 7, -6.7, [s], { y, h: H, door });
    r.doorWall(6.7, -6.4, 6.7, 6.4, [e], { y, h: H, door }); r.doorWall(-6.7, -6.4, -6.7, 6.4, [w], { y, h: H, door });
  };
  atrium(0, true, -3, 3, 3, -3); atrium(Y, false, 2, -3, -2, 3);

  // Углы: стены к улицам, двери в комнаты; четыре калитки вертушкой рвут прямые улицы.
  const D = (x1, z1, x2, z2, at, y = 0) => r.doorWall(x1, z1, x2, z2, at, { y, h: H });
  // Северо-восток: ярус 0 — подножие марша, верх — комната рядом с шахтой.
  D(10.1, 10.4, 10.1, 16.8, [13]); D(6.7, 10.1, 16.8, 10.1, [8.4]);
  D(10.1, 10.4, 10.1, 16.8, [13], Y); r.wall(9.8, 10.1, 13.8, 10.1, { y: Y, h: H }); r.wall(14.1, 9.8, 14.1, 16.8, { y: Y, h: H });
  // Юго-запад: то же, повёрнутое.
  D(-10.1, -16.8, -10.1, -10.4, [-13]); D(-16.8, -10.1, -6.7, -10.1, [-8.4]);
  D(-10.1, -16.8, -10.1, -10.4, [-13], Y); r.wall(-13.8, -10.1, -9.8, -10.1, { y: Y, h: H }); r.wall(-14.1, -16.8, -14.1, -9.8, { y: Y, h: H });
  // Северо-запад и юго-восток: караулки на обоих этажах, калитки на улицах внизу.
  D(-10.1, 10.4, -10.1, 16.8, [13]); D(-16.8, 10.1, -9.8, 10.1, [-13]); D(-10.1, 7, -10.1, 9.8, [8.4]);
  D(10.1, -16.8, 10.1, -10.4, [-13]); D(9.8, -10.1, 16.8, -10.1, [13]); D(10.1, -9.8, 10.1, -7, [-8.4]);
  D(-10.1, 10.4, -10.1, 16.8, [13], Y); D(-16.8, 10.1, -9.8, 10.1, [-13], Y);
  D(10.1, -16.8, 10.1, -10.4, [-13], Y); D(9.8, -10.1, 16.8, -10.1, [13], Y);

  // Атриум внутри: стол поста, парапет галереи с разрывом у марша.
  r.prop('Стол', -1.6, 0, 0.9, 1.8, 0.8); r.prop('Табурет', -2.4, 0.5, 0.45, 0.45, 0.45); r.prop('Табурет', -0.8, -0.5, 0.45, 0.45, 0.45);
  r.chest('SmallOakChest', -5.6, 5.4, { ry: 135 });
  for (const [x, z, w, d] of [[4.35, 0, 0.3, 8.7], [-4.35, 0, 0.3, 8.7], [0, -4.35, 8.4, 0.3], [-1.3, 4.35, 5.8, 0.3]]) r.prop('Парапет', x, z, w, d, 1, { y: Y });
  // Камеры: койки, кости, сундуки в паре камер.
  for (const [x, z] of [[-5.6, 15.75], [0.8, 15.75], [16.3, 4.5], [-16.3, -0.8], [5, -15.75]]) r.prop('Койка', x, z, 1, 2.1, 0.6);
  for (const [x, z] of [[4, 15.5], [-15.5, 4.5], [15.5, -4.5]]) r.prop('Кости', x, z, 1.2, 1.2, 0.2);
  for (const [x, z] of [[-3.8, 15.75], [3.8, 15.75], [16.3, 0.8], [-16.3, 5.6], [-3.8, -15.75]]) r.prop('Койка', x, z, 1, 2.1, 0.6, { y: Y });
  r.chest('Crate', -1, 15.9, { ry: 180 }); r.chest('SmallOakChest', -15.9, 1, { ry: 90 }); r.chest('LargeOakChest', 15.8, 5, { y: Y, ry: 270 }); r.chest('Crate', 3.8, -15.8, { y: Y });
  // Караулки.
  r.prop('Стол', -13, 14, 1.8, 0.9, 0.8); r.prop('Стойка с оружием', -16.2, 12.5, 0.6, 2.4, 2); r.prop('Койка', 16.3, -14.5, 1, 2.1, 0.6);
  r.prop('Стол', 13, -13.5, 0.9, 1.8, 0.8, { y: Y }); r.prop('Койка', 16.3, -14.5, 1, 2.1, 0.6, { y: Y }); r.prop('Стойка с оружием', -16.2, 13, 0.6, 2.4, 2, { y: Y });
  r.chest('GoldenChest', -15.6, 15.6, { y: Y, ry: 135 });
  // Укрытия на верхних улицах.
  r.prop('Обломки', 9.3, 2.4, 0.9, 1.6, 1, { y: Y }); r.prop('Обломки', -7.5, -5, 0.9, 1.6, 1, { y: Y });
  r.brazier(-4.8, 2); r.torch(0, 7, 0); r.torch(0, -7, 180); r.torch(7, 8.4, 90); r.torch(-7, -8.4, 270); r.torch(7, 0, 90, Y); r.torch(-7, 0, 270, Y); r.torch(-16.4, 13, 90, Y);
  r.monster('Warrior', 2, -5, { ry: 0 }); r.monster('Sword', 8.4, 0, { ry: 180 }); r.monster('Sword', -8.4, 3, { ry: 0 }); r.monster('Archer', 0, 5.5, { y: Y, ry: 180 }); r.monster('Crossbow', 8.4, -8.4, { y: Y, ry: 270 });
  r.start(-12.5, 8.4, 90);
};
