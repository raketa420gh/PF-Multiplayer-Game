// Ристалище: овальная яма на −5, в неё спускают только две железные клети на цепях в торцах овала. Кольцо зрителей на уровне
// проёмов, на севере трибуны с ложей, на юге казарма, тренировочный двор и ставочная контора под верхней галереей.
const PIT = -5, T = 6.5, WT = 1.2, MID = WT / 2;
// Четверть овала по внутренней грани стены ямы: торец с клетью, три скошенные грани, длинная сторона с нишей.
const Q = [[12, 2.3], [10.6, 4.7], [7.4, 6.9], [3, 8]];
const POLY = [...Q, ...Q.slice().reverse().map(([x, z]) => [-x, z]), ...Q.map(([x, z]) => [-x, -z]), ...Q.slice().reverse().map(([x, z]) => [x, -z])];
const EDGES = POLY.map((a, i) => {
  const b = POLY[(i + 1) % POLY.length], dx = b[0] - a[0], dz = b[1] - a[1], len = Math.hypot(dx, dz);
  return { a, b, dx, dz, len, n: [dz / len, -dx / len] };
});
const prev = i => EDGES[(i + EDGES.length - 1) % EDGES.length];
/// Вершины овала, отодвинутого наружу на d.
const offset = d => EDGES.map((e, i) => {
  const p = prev(i), cp = p.n[0] * e.a[0] + p.n[1] * e.a[1] + d, ce = e.n[0] * e.a[0] + e.n[1] * e.a[1] + d, det = p.n[0] * e.n[1] - p.n[1] * e.n[0];
  return [(cp * e.n[1] - ce * p.n[1]) / det, (p.n[0] * ce - e.n[0] * cp) / det];
});
const halfWidth = (pts, z) => Math.max(...pts.map((a, i) => {
  const b = pts[(i + 1) % pts.length];
  return (a[1] - z) * (b[1] - z) > 0 || a[1] === b[1] ? -Infinity : a[0] + (b[0] - a[0]) * (z - a[1]) / (b[1] - a[1]);
}));

