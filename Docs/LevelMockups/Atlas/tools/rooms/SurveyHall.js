// Новая: рельефный макет яруса 7×7 на полу зала, балкон обхода, три плиты на вершинах открывают яму Ствола в кабинет на −6.
const CELL = 3, ORG = -10.5, SLIT = 1.7, BALC = 5, STUDY = -6, PIT = -1.25, TOP = 9;
const edge = i => ORG + CELL * i;
const lo = i => i === 0 ? ORG : edge(i) + SLIT / 2, hi = i => i === 6 ? -ORG : edge(i + 1) - SLIT / 2;
// Блоки макета: столбцы c1..c2, строки r1..r2 (0 — юг), верх. Перепады между связанными блоками ≤ 0,25.
const BLOCKS = {
  A: [0, 1, 6, 6, 1], B: [2, 2, 6, 6, 1.25], C: [3, 4, 6, 6, 1.25], D: [5, 6, 6, 6, 1.4],
  E: [0, 0, 5, 5, 1.25], F: [1, 2, 5, 5, 1.25], G: [3, 3, 5, 5, 1], H: [4, 6, 5, 5, 1.25],
  I: [0, 1, 3, 4, 1.4], J: [2, 2, 3, 4, 1.15], K: [4, 4, 4, 4, 1], L: [5, 6, 3, 4, 1.25], M: [4, 4, 3, 3, 1.25],
  N: [0, 0, 1, 2, 1.25], O: [1, 3, 2, 2, 1.15], P: [4, 5, 2, 2, 1], Q: [6, 6, 1, 2, 1.25],
  R: [1, 1, 0, 1, 1], S: [2, 3, 1, 1, 1], T: [4, 4, 0, 1, 1.15], U: [5, 5, 1, 1, 1.25],
  V: [0, 0, 0, 0, 1.4], W: [2, 3, 0, 0, 1.25], X: [5, 6, 0, 0, 1.4],
};
// Перемычки по верху: 'v' — через вертикальную щель b в строке r, 'h' — через горизонтальную щель b в столбце c; верх.
const DAMS = [['v', 5, 6, 1.25], ['h', 6, 4, 1.25], ['h', 5, 5, 1.25], ['v', 5, 3, 1.25], ['h', 3, 6, 1.25], ['v', 6, 1, 1.25], ['h', 1, 5, 1.25],
  ['h', 1, 2, 1.25], ['h', 2, 3, 1.15], ['v', 1, 2, 1.25], ['h', 3, 0, 1.25], ['h', 5, 0, 1.25], ['v', 1, 5, 1.25], ['h', 6, 2, 1.25], ['v', 3, 6, 1.25]];

exports.options = {};
exports.build = r => {
  r.desc('На полу зала 26 × 26 м лежит рельефный макет всего этажа 7 × 7 клеток по 3 м: блоки высотой 1–1,4 м разделены щелями 1,7 м, а по верху их связывают перемычки, поэтому по рельефу можно бежать кольцом вокруг ямы Ствола, не спускаясь в щели. На макет ведут три коротких марша с трёх сторон, они же рвут обход у подножия. На +5 вокруг идёт балкон на столбах, он разомкнут над западным маршем, с него макет читается как карта, на его полу лежат засечки против трёх вершин. Три плиты на этих вершинах, нажатые по порядку, сдвигают крышку ямы, и лестница уходит на −6 в кабинет главного маркшейдера с сейфовой за дверью. По сторонам зала восемь комнаток с планами и инструментами принимают проёмы, из каждой одна дверь в зал; в восточной поднимается второй марш на балкон.');
  const low = r.level(STUDY), g = r.level(0, TOP);
  g.carve(-13, -13, 13, 13);

  // Макет.
  for (const [c1, c2, r1, r2, top] of Object.values(BLOCKS)) r.platform(lo(c1), lo(r1), hi(c2), hi(r2), top);
  for (const [kind, b, n, top] of DAMS) {
    const a = edge(b) - SLIT / 2, c = edge(b) + SLIT / 2;
    kind === 'v' ? r.platform(a, lo(n), c, hi(n), top) : r.platform(lo(n), a, hi(n), c, top);
  }
  // Марши на макет: они же перекрывают обход у подножия.
  r.stairs(2, 11.35, 2.2, 1.7, 1.25, 180);
  r.stairs(11.35, -4.5, 2.2, 1.7, 1.25, 270);
  r.stairs(-2, -11.35, 2.2, 1.7, 1.25, 0);

  // Яма Ствола: две клетки, спуск к крышке, под ней марш к кабинету.
  g.hole(-1.5, -1.5, 1.5, 4.5);
  low.carve(-1.5, -2.8, 1.5, 4.5);
  r.stairs(0, 3.7, 3, 1.6, 1.25, 0, PIT);
  r.stairs(0, 0.05, 3, 5.7, 4.75, 0, STUDY);
  r.secretDoor(0, PIT - 0.4, 0.7, 3, 0.4, 4.4, [-3.4, 0, 0]);

  // Плиты на трёх вершинах, засечки на балконе против них.
  r.plate(8.5, -9.4, 1, { y: 1.4 });
  r.plate(-7.6, 2.8, 2, { y: 1.4 });
  r.plate(8.5, 9.4, 3, { y: 1.4 });
  const notches = (x, z, n, alongX) => { for (let i = 0; i < n; i++) r.prop('Засечка', x + (alongX ? i * 0.35 : 0), z + (alongX ? 0 : i * 0.35), alongX ? 0.12 : 0.7, alongX ? 0.7 : 0.12, 0.12, { y: BALC }); };
  notches(8.2, -12, 1, true);
  notches(-12, 5.6, 2, false);
  notches(12, 9.2, 3, false);
  r.drop(4, TOP - 0.4, 12);
  r.drop(-12, TOP - 0.4, -8);

  // Балкон обхода: разомкнут над западным маршем.
  r.slab(-13, 3, -10.9, 13, BALC);
  r.slab(-10.9, 10.9, 13, 13, BALC);
  r.slab(10.9, -10.9, 13, 10.9, BALC);
  r.slab(-13, -13, 13, -10.9, BALC);
  r.slab(-13, -10.9, -10.9, -3, BALC);
  r.stairs(-12, 0, 2, 6, BALC, 0);
  for (const [x, z, w, d] of [[-10.75, 7, 0.3, 8], [0, 10.75, 21.8, 0.3], [10.75, 0, 0.3, 21.8], [0, -10.75, 21.8, 0.3], [-10.75, -7, 0.3, 8], [-12, -2.85, 2.2, 0.3]]) r.prop('Парапет', x, z, w, d, 1, { y: BALC });
  for (const t of [-9, 9]) { r.column(t, 11.2, { s: 0.6, h: BALC - 0.6 }); r.column(t, -11.2, { s: 0.6, h: BALC - 0.6 }); r.column(11.2, t, { s: 0.6, h: BALC - 0.6 }); r.column(-11.2, t, { s: 0.6, h: BALC - 0.6 }); }
  r.column(-3, 11.2, { s: 0.6, h: BALC - 0.6 }); r.column(5, -11.2, { s: 0.6, h: BALC - 0.6 }); r.column(11.2, 2, { s: 0.6, h: BALC - 0.6 });

  // Комнатки: у каждой одна дверь в зал, в стороне от своего проёма.
  const gate = (x, z, alongX) => {
    alongX ? g.carve(x - 1, z - 0.3, x + 1, z + 0.3) : g.carve(x - 0.3, z - 1, x + 0.3, z + 1);
    r.door(x, z, alongX ? 0 : 90);
    r.block(x, z, alongX ? 2 : 0.6, alongX ? 0.6 : 2, { y: 2.4, h: TOP - 2.4 });
  };
  g.carve(-12.6, 13.6, -3, 16.8); gate(-5, 13.3, true);
  g.carve(3, 13.6, 12.6, 16.8); gate(5.6, 13.3, true);
  g.carve(-12.6, -16.8, -4, -13.6); gate(-11, -13.3, true);
  g.carve(2, -16.8, 12.6, -13.6); gate(4, -13.3, true);
  g.carve(-16.8, 3, -13.6, 12.6); gate(-13.3, 6, false);
  g.carve(-16.8, -12.6, -13.6, -3); gate(-13.3, -6.5, false);
  g.carve(13.6, 0.8, 16.8, 12.6); gate(13.3, 10.8, false);
  g.carve(13.6, -12.6, 16.8, -3); gate(13.3, -5, false);
  // Перегородки: тамбур в самой длинной комнате и чертёжная за дверью.
  r.doorWall(-6, 13.6, -6, 16.8, [15.2], { h: 3.2 });
  r.doorWall(6, -16.8, 6, -13.6, [-15.2], { h: 3.2 });

  // Восточный марш на балкон: из комнаты, площадка и дверь на +5.
  r.stairs(14.6, 5.8, 1.8, 6, BALC, 180);
  r.slab(13.6, 0.8, 16.8, 2.8, BALC);
  r.slab(13, 0.8, 13.6, 2.8, BALC);
  g.carve(13, 0.8, 13.6, 2.8);
  r.block(13.3, 1.8, 0.6, 2, { y: 0, h: BALC - 0.6 });
  r.door(13.3, 1.8, 90, { y: BALC });
  r.block(13.3, 1.8, 0.6, 2, { y: BALC + 2.4, h: TOP - BALC - 2.4 });
  r.block(15.2, 1.8, 3.2, 2, { y: 0, h: BALC - 0.6 });

  // Кабинет главного маркшейдера и сейфовая.
  low.carve(-7, -10, 7, -2.8);
  r.doorWall(2.6, -10, 2.6, -2.8, [-8], { y: STUDY, h: 5.4 });
  r.prop('Стол', -2, -7, 3, 1.4, 0.9, { y: STUDY });
  r.prop('Стеллаж', -6.6, -6.4, 0.6, 5, 3, { y: STUDY });
  r.prop('Стеллаж', -4, -9.6, 4, 0.6, 3, { y: STUDY });
  r.prop('Полки с припасами', 1, -9.6, 2.2, 0.6, 2.2, { y: STUDY });
  r.chest('Bookshelf', -6.4, -3.4, { y: STUDY, ry: 90 });
  r.chest('LargeOakChest', -2, -8.2, { y: STUDY, ry: 0 });
  r.chest('GoldenChest', 6, -9, { y: STUDY, ry: 315 });
  r.chest('GoldPile', 4.2, -9.2, { y: STUDY });
  r.chest('GoldPile', 6.2, -7, { y: STUDY });
  r.trap('Vent', 0, -3.6, { y: STUDY });
  r.trap('Spike', -3.8, -4.4, { y: STUDY });
  r.trap('Blade', 2.6, -8, { y: STUDY, ry: 0 });
  r.trap('Spike', 4.2, -7, { y: STUDY });
  r.trap('Spike', 5, -5.4, { y: STUDY });

  // Комнатки: планы и инструменты.
  r.prop('Стол', -10, 15.2, 2.4, 1.2, 0.9); r.chest('Bookshelf', -4, 16.2, { ry: 180 });
  r.prop('Стеллаж', 12.2, 15.2, 0.6, 2.6, 3); r.prop('Стеллаж', 5.2, 16.4, 3, 0.6, 3); r.chest('SmallOakChest', 3.6, 15.8, { ry: 90 });
  r.prop('Стол', -6, -16, 2.4, 0.9, 0.9); r.prop('Теодолит', -5.2, -14.4, 0.5, 0.5, 1.5, { round: true });
  r.prop('Теодолит', 11.6, -14.2, 0.5, 0.5, 1.5, { round: true }); r.prop('Полки с припасами', 5.6, -16.4, 2.6, 0.6, 2.2); r.chest('Crate', 11.8, -16);
  r.prop('Стол', -15.2, 11, 1.2, 2.4, 0.9); r.prop('Полки с припасами', -16.4, 4.6, 0.6, 2.6, 2.2);
  r.prop('Стеллаж', -16.4, -4.6, 0.6, 2.6, 3); r.chest('Bookshelf', -15.6, -12, { ry: 0 });
  r.prop('Мешки', 16, 11.8, 1, 1.4, 0.8); r.chest('Crate', 14.4, 12);
  r.prop('Стол', 15.2, -11.4, 1.2, 1.8, 0.9); r.chest('SmallOakChest', 15.8, -3.8, { ry: 180 });

  // Ловушки: только у ямы и вершин.
  r.trap('Spike', -3, 2);
  r.trap('Spike', 3, -3);
  r.trap('Spike', 7.4, -4.5);
  r.chest('SmallOakChest', -12, -11.8, { y: BALC, ry: 90 });
  r.chest('Urn', -12, 8, { y: BALC });

  // Свет: балкон и углы зала, в щелях темно.
  r.torch(-12.9, 8, 90);
  r.torch(12.9, -8, 270);
  r.brazier(0, 12, BALC);
  r.brazier(0, -12, BALC);
  r.brazier(12, 0, BALC);
  r.candle(-9.8, 15.2, 0.9);
  r.brazier(-5.4, -4.2, STUDY);
  r.candle(4.2, -3.6, STUDY);

  r.monster('Sword', -4.5, -7.5, { ry: 0 });
  r.monster('Archer', -12, 11.8, { y: BALC, ry: 135 });
  r.monster('Crossbow', 12, -11.8, { y: BALC, ry: 315 });
  r.monster('Sword', 3, 8.8, { y: 1.25, ry: 180 });
  r.monster('Mage', -2, -5, { y: STUDY, ry: 180 });
  r.monster('Warrior', 5, -7.6, { y: STUDY, ry: 90 });
  r.start(8.4, 15.4, 180);
};
