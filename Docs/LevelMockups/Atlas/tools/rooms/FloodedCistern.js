// Правка: почти всё в воде, одна извилистая дорожка по диагонали из редких плит, две точки интереса с препятствиями в углах и одна по центру.
const STONE = 0.25;
// Плиты дорожки по порядку от юго-западного острова к северо-восточному, через центр; зазор 0,6 м или вплотную.
const PATH = [
  [-10.4, -13, -8.4, -11.2], [-10.4, -10.6, -8.6, -8.6], [-8, -10, -6, -8.2], [-7.6, -7.6, -5.8, -5.6], [-5.2, -7, -3.4, -5.2], [-5, -4.6, -3.2, -1.6],
  [1, 4, 2.8, 5.8], [3.4, 4.6, 5.2, 6.2], [5.2, 5.2, 7, 7], [5.6, 7.6, 7.4, 9.4], [8, 8.2, 9.8, 10.2], [8.2, 10.8, 10, 12.8],
];

exports.options = {};
exports.build = r => {
  r.desc('Затопленная цистерна: вся клетка залита по колено, вода замедляет, редкие колонны стоят прямо в ней. По диагонали с юго-запада на северо-восток вьётся единственная сухая дорожка из редких каменных плит с шагом 0,6 м. Она связывает три острова: разбитый водосборник в юго-западном углу, затопленную часовню в северо-восточном и колодец на центральном острове с золотым сундуком. Со всех восьми проёмов идёшь по воде, а на дорожку и острова надо ещё добраться.');
  const g = r.level(0);
  g.carve(-16.8, -16.8, 16.8, 16.8);
  r.water(-16.8, -16.8, 16.8, 16.8);
  for (const p of PATH) r.platform(...p, STONE);

  // Юго-запад: разбитый водосборник, сундук за проломленной стенкой.
  r.platform(-16.8, -16.8, -11, -11, STONE);
  r.wall(-15.6, -12.4, -12.4, -12.4, { y: STONE, h: 2.6 });
  r.wall(-12.4, -16.8, -12.4, -14.8, { y: STONE, h: 2.6 });
  r.prop('Обломки', -12.2, -13.6, 1, 1.2, 0.9, { y: STONE, ry: 20 });
  r.column(-14.2, -14.2, { s: 0.9, y: STONE, h: 3.2, round: true });
  r.chest('LargeOakChest', -15.8, -15.8, { y: STONE, ry: 45 });
  r.chest('Barrel', -15.8, -13.4, { y: STONE, ry: 0 });

  // Центр: колодец в кольце разбитых стенок, входы с запада и с северо-востока.
  r.platform(-2.6, -3, 3.4, 3.4, STONE);
  r.wall(-2, -2.4, 2.8, -2.4, { y: STONE, h: 2.4 });
  r.wall(2.8, -2.1, 2.8, 0.8, { y: STONE, h: 2.4 });
  r.wall(-2, 2.8, 0.2, 2.8, { y: STONE, h: 2.4 });
  r.prop('Парапет', 0.4, 0.2, 1.8, 0.3, 0.9, { y: STONE });
  r.prop('Парапет', 0.4, -1.1, 1.8, 0.3, 0.9, { y: STONE });
  r.prop('Парапет', -0.35, -0.45, 0.3, 1, 0.9, { y: STONE });
  r.prop('Парапет', 1.15, -0.45, 0.3, 1, 0.9, { y: STONE });
  r.chest('GoldenChest', 1.8, 1.8, { y: STONE, ry: 225 });
  r.chest('Urn', -1.4, 1.8, { y: STONE, ry: 0 });

  // Северо-восток: затопленная часовня с дверным проёмом с запада.
  r.platform(10.6, 11, 16.8, 16.8, STONE);
  r.doorWall(12.6, 12.4, 12.6, 15.6, [14], { y: STONE, h: 3.2, door: false });
  r.wall(12.3, 12.4, 16.8, 12.4, { y: STONE, h: 3.2 });
  r.wall(12.3, 15.8, 14.2, 15.8, { y: STONE, h: 3.2 });
  r.prop('Алтарь', 15.6, 14.2, 1, 2.2, 1, { y: STONE });
  r.chest('LargeOakChest', 13.6, 15, { y: STONE, ry: 90 });
  r.chest('Coffin', 14.4, 13.4, { y: STONE, ry: 0 });
  r.prop('Обломки', 11.6, 15.6, 1.2, 1, 0.9, { y: STONE, ry: 30 });

  // Редкие колонны в воде, по углам без дорожки.
  for (const [x, z] of [[-11, 3.6], [-5, 9.4], [-13, 13], [5, -9.4], [11, -3.6], [13, -13], [-9, -2], [9, 1.4]]) r.column(x, z, { s: 1, round: true });

  r.torch(-16.6, -9.8, 90);
  r.torch(9.8, 16.6, 180);
  r.torch(16.6, -0.6, 270);
  r.torch(-0.6, 16.6, 180);
  r.brazier(-13.4, -14.8, STONE);
  r.brazier(-1, -0.5, STONE);
  r.candle(15.2, 15.2, STONE);

  r.monster('Sword', -6.4, 6, { ry: 135 });
  r.monster('Sword', 7, -6.4, { ry: 315 });
  r.monster('Skull', -9.6, -9.6, { y: STONE, ry: 45 });
  r.monster('Warrior', 0, 1.4, { y: STONE, ry: 180 });
  r.monster('Archer', 14, 14, { y: STONE, ry: 225 });
  r.start(8.4, -14.6, 0);
};
