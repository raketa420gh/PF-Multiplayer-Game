  r.mat('studs', () => { r.block(-8.5, 2.8, 1.8, 3.2, { h: 2.4 }); r.doorWall(-15, -0.4, -9.8, -0.4, [-13.6], { th: 0.3, y: G, h: 2.5 }); });   // дровник; перегородка спален
  r.mat('stone', () => r.block(-10.3, 2.8, 1, 1.8, { h: 7.3 }));
  rail(-14.9, -0.25, 0.2, 4.5, G); rail(-15.9, -2.6, 1.8, 0.2, G);
