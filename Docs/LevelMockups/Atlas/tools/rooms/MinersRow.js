// Новая: подземный посёлок, кривые улочки между двухэтажными домами, площадь с колодцем, мостки по плоским крышам.
const { subtract, rect } = require('../roomkit');
const RY = { N: 0, E: 90, S: 180, W: 270 }, EDGE = 16.8;

exports.options = {};
exports.build = r => {
  r.desc('Зал 12 м, в нём посёлок смены: девять домов разного размера и высоты, сарай, двухэтажный трактир и лавка стоят вплотную к стенам клетки и рвут периметр, между ними кривые улочки 2–3 м. Посередине площадь с колодцем, в неё выходит трактир, с площади внешняя лестница поднимается на его балкон. У каждого дома своя дверь и лестница, внутри крошечные комнаты за дверьми. Крыши на 5,8–6,8 м; на шесть из них можно подняться люками из трактира и западного дома, дощатые мостки ведут поверху через полпосёлка.');
  r.level(0, 12).carve(-EDGE, -EDGE, EDGE, EDGE);

  const flight = ([x1, z1, x2, z2, dir], rise, y0 = 0) => {
    const q = rect(x1, z1, x2, z2), ns = dir === 'N' || dir === 'S';
    r.stairs((q.x1 + q.x2) / 2, (q.z1 + q.z2) / 2, ns ? q.x2 - q.x1 : q.z2 - q.z1, ns ? q.z2 - q.z1 : q.x2 - q.x1, rise, RY[dir], y0);
  };
  // Пролёт в перекрытии: длина марша и ещё 0,5 м за его нижним торцом (перекрытие ниже 3,5 м над маршем).
  const well = ([x1, z1, x2, z2, dir]) => rect(x1 - (dir === 'E' ? 0.5 : 0), z1 - (dir === 'N' ? 0.5 : 0), x2 + (dir === 'W' ? 0.5 : 0), z2 + (dir === 'S' ? 0.5 : 0));
  const slabs = (area, y, hole) => subtract(area, hole ? [well(hole)] : []).forEach(q => r.slab(q.x1, q.z1, q.x2, q.z2, y));
  // Дом: стены на всю высоту, этаж f со стеной лестницы st, крыша top с люком hatch; у стен клетки своей стены нет.
  const house = (x1, z1, x2, z2, { f = 0, top, N = [], S = [], E = [], W = [], st, hatch, noW }) => {
    const h = top - 0.6, o = { th: 0.4, h }, a = x1 <= -EDGE ? x1 : x1 + 0.2, b = x2 >= EDGE ? x2 : x2 - 0.2, c = z1 <= -EDGE ? z1 : z1 + 0.2, d = z2 >= EDGE ? z2 : z2 - 0.2;
    if (z2 < EDGE) r.doorWall(Math.max(x1 - 0.2, -EDGE), z2, Math.min(x2 + 0.2, EDGE), z2, N, o);
    if (z1 > -EDGE) r.doorWall(Math.max(x1 - 0.2, -EDGE), z1, Math.min(x2 + 0.2, EDGE), z1, S, o);
    if (x2 < EDGE) r.doorWall(x2, c, x2, d, E, o);
    if (x1 > -EDGE && !noW) r.doorWall(x1, c, x1, d, W, o);
    if (f) { slabs(rect(a, c, b, d), f, st); flight(st, f); }
    slabs(rect(Math.max(x1 - 0.3, -EDGE), Math.max(z1 - 0.3, -EDGE), Math.min(x2 + 0.3, EDGE), Math.min(z2 + 0.3, EDGE)), top, hatch);
    if (hatch) flight(hatch, top - f, f);
  };
  // Перегородка: до нижней грани перекрытия, в ней дверь.
  const part = (x1, z1, x2, z2, at, y, h) => r.doorWall(x1, z1, x2, z2, at, { th: 0.3, y, h: Math.max(h, 2.5) });
  const bed = (x, z, ry, y = 0) => r.prop('Койка', x, z, 0.9, 1.9, 0.5, { y, ry }), table = (x, z, y = 0) => r.prop('Стол', x, z, 1.2, 0.8, 0.8, { y }), stool = (x, z, y = 0) => r.prop('Табурет', x, z, 0.4, 0.4, 0.45, { y }), shelf = (x, z, w, d, y = 0) => r.prop('Полки с припасами', x, z, w, d, 2, { y }), barrels = (x, z) => r.prop('Бочки', x, z, 1.3, 1.3, 1.2), crates = (x, z) => r.prop('Штабель ящиков', x, z, 1.3, 1.3, 1.8);

  // ---------- Северный ряд ----------
  house(-16.8, 10, -10, 16.8, { f: 3, top: 6.2, E: [12.2], st: [-15.2, 15, -11.5, 16.8, 'W'] });
  part(-13.4, 10.2, -13.4, 15, [12.4], 0, 2.4);
  bed(-15.6, 12, 0); table(-11.4, 11, 0); r.chest('SmallOakChest', -15.8, 14.2, { ry: 90 }); bed(-15, 11.4, 90, 3); shelf(-12, 10.6, 3, 0.5, 3);

  house(-6, 7.6, 0, 16.8, { f: 3.2, top: 6.4, W: [10.6], E: [14.8], st: [-2, 9.4, -0.2, 13.2, 'N'] });
  part(-5.8, 13.2, -2, 13.2, [-3.9], 0, 2.6); part(-5.8, 10.8, -2, 10.8, [-3.9], 3.2, 2.6);
  table(-4.8, 8.6); stool(-3.6, 8.6); bed(-5, 15.2, 90); shelf(-2.2, 16.2, 3, 0.5); bed(-5, 8.8, 90, 3.2); r.chest('Crate', -5.2, 12.2, { y: 3.2 }); r.prop('Очаг', -3.2, 8.2, 1.6, 0.9, 1.1);

  house(2, 10.4, 7, 16.8, { f: 3, top: 6.2, S: [3.5], st: [5, 12, 6.8, 15.7, 'N'] });
  part(2.2, 13.6, 5, 13.6, [3.6], 0, 2.4);
  bed(2.9, 15.2, 0); stool(5.6, 11); bed(3.4, 11.6, 0, 3); r.chest('SmallOakChest', 3.4, 15.8, { y: 3, ry: 180 });

  house(10, 10.6, 16.8, 16.8, { f: 3.6, top: 6.8, W: [12.4], st: [11.4, 15, 15.7, 16.8, 'E'] });
  part(13.4, 10.8, 13.4, 15, [12.9], 0, 3);
  table(11.8, 11.4); stool(11.8, 12.4); bed(15.6, 12.8, 0); r.prop('Котёл', 15.4, 15.8, 1, 1, 1); r.chest('LargeOakChest', 15.8, 11.4, { y: 3.6, ry: 270 }); bed(11, 12.8, 0, 3.6);

  // ---------- Южный ряд ----------
  house(-16.8, -16.8, -10.6, -10.4, { f: 3, top: 5.8, E: [-12.6], st: [-15.4, -16.8, -11.7, -15, 'W'] });
  part(-13.6, -15, -13.6, -10.6, [-12.8], 0, 2.4);
  bed(-15.5, -12.6, 0); table(-11.6, -11.2); r.chest('Crate', -15.8, -11.2); bed(-13, -12, 90, 3);

  house(-7, -16.8, -0.6, -7.6, { f: 3, top: 6, W: [-10.5], E: [-14.6], st: [-2.7, -13.1, -0.8, -9.4, 'S'] });
  part(-6.8, -13.1, -2.7, -13.1, [-4.7], 0, 2.4);
  table(-5.4, -8.6); stool(-4.2, -8.6); bed(-6, -15.4, 90); bed(-3.4, -15.6, 90); shelf(-6.4, -11, 0.5, 3, 3); r.chest('Crate', -5.8, -15.8, { y: 3 });

  house(2, -16.8, 7, -9.8, { top: 3.4, N: [4.5] }); // сарай
  crates(3, -15.8); crates(6, -15.6); r.prop('Рудная вагонетка', 4.5, -13.6, 1.3, 2, 1.2); r.chest('Barrel', 2.8, -11);

  house(10.2, -16.8, 16.8, -10.8, { f: 3.2, top: 6, W: [-13], st: [11.6, -16.8, 15.4, -15, 'E'] });
  bed(15.8, -12, 0); table(11.2, -11.8); shelf(13.4, -11.2, 3, 0.5); bed(12, -12.4, 90, 3.2); r.chest('SmallOakChest', 15.8, -15.8, { y: 3.2, ry: 270 });

  // ---------- Запад: большой дом с люком на крышу ----------
  house(-16.8, -2.6, -8.2, 6, { f: 3, top: 6.2, E: [1.4], st: [-13.4, 4, -9.7, 5.8, 'W'], hatch: [-16.7, -1, -14.9, 2.8, 'S'] });
  part(-12.2, -2.4, -12.2, 4, [0.8], 0, 2.4); part(-12.4, -2.4, -12.4, 4, [1], 3, 2.6);
  table(-10, -1.4); stool(-11, -1.4); bed(-15.6, -1, 0); bed(-14.4, -1, 0); r.prop('Очаг', -15.9, 3.2, 1, 1.6, 1.1); bed(-9.4, 2, 0, 3); r.chest('LargeOakChest', -9.4, -1.8, { y: 3, ry: 270 });

  // ---------- Восток ----------
  house(11.6, -4.6, 16.8, 3.8, { f: 3.4, top: 6.6, W: [-2.6], st: [15, -2.6, 16.8, 1.4, 'N'] });
  part(11.8, 1.4, 15, 1.4, [13.4], 0, 2.8);
  table(12.6, 2.6); stool(13.8, 2.6); bed(14, -0.4, 0, 3.4); r.chest('Crate', 12.4, 2.8, { y: 3.4 });

  // ---------- Лавка на площади ----------
  house(-5.2, -7.2, -0.4, -2.8, { top: 3.8, N: [-1.8] });
  r.prop('Стол', -3.9, -5.2, 2.4, 0.7, 1); shelf(-3, -6.8, 4, 0.5); r.chest('LargeOakChest', -4.6, -6.2, { ry: 180 });

  // ---------- Трактир: зал и кухня внизу, номера и коридор наверху, люк на крышу ----------
  const F = 3.2;
  house(1.4, -5, 8.8, 5.8, { f: F, top: 6.4, E: [4.4], st: [6.7, -2.8, 8.6, 1, 'S'], hatch: [4.4, 3.4, 8.2, 5.4, 'E'], noW: true });
  // Западный фасад: двойная дверь на площадь внизу, дверь на балкон наверху.
  r.doorWall(1.4, -4.8, 1.4, 5.6, [-1.8], { th: 0.4, h: F, double: true }); r.doorWall(1.4, -4.8, 1.4, 5.6, [4.2], { th: 0.4, y: F, h: 6.4 - 0.6 - F });
  part(1.6, 2.6, 8.6, 2.6, [5.2], 0, 2.6); part(1.6, 3, 8.6, 3, [3], F, 2.6); part(1.6, -1, 6.7, -1, [3.5], F, 2.6);
  flight([-0.6, -0.6, 1.2, 3.2, 'N'], F);
  r.slab(-0.6, 3.2, 1.2, 5.2, F);
  r.prop('Парапет', -0.7, 4.2, 0.2, 2.2, 1, { y: F }); r.prop('Парапет', 0.3, 5.3, 2, 0.2, 1, { y: F });
  table(3.4, -3.4); stool(2.4, -3.4); stool(4.4, -3.4); table(3.4, 0.8); stool(2.4, 0.8); stool(4.4, 0.8);
  r.prop('Стойка', 5.6, -3.2, 0.7, 2.8, 1.1); r.prop('Бочки', 7.6, -4.2, 1.6, 0.9, 1.2); r.prop('Очаг', 2.6, 5, 1.8, 0.9, 1.1); r.prop('Котёл', 4.4, 5, 1.1, 1.1, 1); shelf(2, 3.6, 0.5, 1.6);
  bed(5.4, -3.6, 90, F); bed(2.4, -3.6, 90, F); bed(2.4, 1.6, 90, F); r.chest('GoldenChest', 2.2, -0.2, { y: F, ry: 90 }); r.chest('GoldPile', 3.4, 0, { y: F });
  r.trap('Spike', 3.6, -1, { y: F }); r.trap('Spike', 3, 3, { y: F });

  // ---------- Мостки по крышам ----------
  r.slab(9.1, -1, 11.3, 0.8, 6.5);        // трактир — восточный дом
  r.slab(3.6, 6.1, 5.4, 10.1, 6.3);       // трактир — северный дом
  r.slab(0.3, 12.2, 1.7, 14, 6.3);        // через проулок
  r.slab(-9.7, 12, -6.3, 13.8, 6.3);      // над северной улицей
  r.slab(-13, 6.3, -11.2, 9.7, 6.2);      // к западному дому
  for (const [x, z, y, h] of [[6, 13, 6.2, 1.1], [-3, 14, 6.4, 1.3], [-14, 12.6, 6.2, 1]]) r.block(x, z, 0.9, 0.9, { y, h }); // трубы
  r.chest('SmallOakChest', 6, 11.4, { y: 6.2, ry: 180 });

  // ---------- Сараи и пристройки: улицы сужаются и ломаются ----------
  r.block(-14.6, -4.1, 4.4, 2.6, { h: 2.8 });
  r.block(4.7, 6.8, 4.6, 1.6, { h: 2.6 });
  r.block(14.4, 4.9, 4.8, 2.2, { h: 3 });
  r.block(14.8, -5.6, 4, 1.6, { h: 2.6 });

  // ---------- Площадь и улицы ----------
  r.prop('Колодец', -3.2, 2, 2.4, 2.4, 1, { round: true });
  r.column(-4.5, 2, { s: 0.3, h: 3 }); r.column(-1.9, 2, { s: 0.3, h: 3 }); r.block(-3.2, 2, 3, 0.3, { y: 3, h: 0.3 });
  r.prop('Скамья', -7.2, -1.6, 0.6, 2.4, 0.5); r.prop('Рудная вагонетка', -10.4, -4.4, 2, 1.2, 1.2, { ry: 20 });
  barrels(-5.2, 6.6); crates(9.8, 9.8); barrels(8.2, -8.8); crates(-9.4, -9.8); barrels(10.2, 5.2); r.prop('Рудная вагонетка', -13, -7, 2, 1.2, 1.2, { ry: 340 }); r.prop('Мешки', 0.6, 8.8, 1.4, 1, 0.8); r.prop('Обломки', -10.6, 7, 1.4, 1, 0.9, { ry: 25 });
  r.chest('Urn', 1, 16); r.chest('Crate', 1, -15.8);

  r.brazier(-5.4, 0.4); r.torch(-6.2, 11, 270); r.torch(7.2, 13.4, 90); r.torch(-7.2, -12, 90); r.torch(10, -13.2, 270); r.torch(9.4, -3, 90); r.torch(-16.6, 8.4, 90); r.brazier(5.4, -2.8);
  r.monster('Sword', -2, 5, { ry: 180 }); r.monster('Sword', 9, -7.4, { ry: 270 }); r.monster('Crossbow', -2, 10, { y: 6.4, ry: 90 }); r.monster('Warrior', 4, 2, { y: 6.4, ry: 180 }); r.monster('Skull', 3, -3.6, { y: F, ry: 90 });
  r.start(-3.4, -0.6, 0);
};
