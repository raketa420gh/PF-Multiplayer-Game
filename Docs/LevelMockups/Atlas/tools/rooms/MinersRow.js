  const toll = house('Мытня', 9.8, -16.8, 16.8, -9.8, { top: 3.8, wall: 'stone', roof: 'stone', sides: { N: { d: [12.2], w: [[15, 1, 1.2, 2.1]] }, W: { w: [[-13.5, 1, 1.2, 2.1]] } } });
