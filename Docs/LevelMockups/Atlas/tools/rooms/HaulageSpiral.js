/// Скала как объём: пустоты с полом и потолком на любой высоте. В каждой полосе яруса клетка, задетая пустотой, вырезается,
/// а всё, что в ней не пустота, возвращается блоками: так туннели идут сквозь перекрытия ярусов.
function solidify(r, bands, voids) {
  const uniq = a => [...new Set(a.map(v => Math.round(v * 1000) / 1000))].sort((p, q) => p - q);
  const xs = uniq(voids.flatMap(v => [v.x1, v.x2])), zs = uniq(voids.flatMap(v => [v.z1, v.z2]));
  for (const { lo, hi, level } of bands) {
    const keys = xs.slice(0, -1).map((x, i) => zs.slice(0, -1).map((z, j) => {
      const cx = (x + xs[i + 1]) / 2, cz = (z + zs[j + 1]) / 2;
      const here = voids.filter(v => cx > v.x1 && cx < v.x2 && cz > v.z1 && cz < v.z2 && v.a < hi && v.b > lo).sort((p, q) => p.a - q.a);
      if (!here.length) return null;
      const out = []; let y = lo;
      for (const v of here) { if (v.a > y) out.push([y, v.a, v.stairs ? 0 : 1]); y = Math.max(y, v.b); }
      if (y < hi) out.push([y, hi, 0]);
      return JSON.stringify(out);
    }));
    for (let i = 0; i < keys.length; i++) for (let j = 0; j < keys[i].length; j++) {
      const k = keys[i][j]; if (k === null) continue;
      let j2 = j; while (j2 + 1 < keys[i].length && keys[i][j2 + 1] === k) j2++;
      let i2 = i; while (i2 + 1 < keys.length) { let same = true; for (let b = j; b <= j2; b++) same = same && keys[i2 + 1][b] === k; if (!same) break; i2++; }
      for (let a = i; a <= i2; a++) for (let b = j; b <= j2; b++) keys[a][b] = null;
      const x1 = xs[i], x2 = xs[i2 + 1], z1 = zs[j], z2 = zs[j2 + 1], cx = (x1 + x2) / 2, cz = (z1 + z2) / 2;
      level.carve(x1, z1, x2, z2).hole(x1, z1, x2, z2);
      for (const [a, b, floor] of JSON.parse(k)) {
        // Скала под маршем ниже его: вровень с низом марша её негодный для ходьбы верх рвёт NavMesh.
        const body = floor ? b - FLOOR : b - 0.4;
        if (body - a > 0.01) r.block(cx, cz, x2 - x1, z2 - z1, { y: a, h: body - a });
        if (floor) r.slab(x1, z1, x2, z2, b);
      }
    }
  }
}

